/// Generates lib/src/term_table.dart from the term table of docs/spec/01-produkt.md
/// section 9 (brief M4-06 Design note 4, docs/DECISIONS.md D-M4-06-5).
///
/// The source is the table between the `language-check: off` and `language-check: on`
/// markers of section 9. test/term_table_test.dart compares the checked-in file with a fresh
/// rendering, so a change of the table without a new generation fails `make test`.
///
/// Usage, from packages/l10n: `dart run tool/term_table.dart`.
library;

import 'dart:io';

import 'package:l10n/src/term_pair.dart';

/// The chapter files that may hold the table, in order: `main` names the chapter in English,
/// the integration bases in German.
const List<String> specCandidates = [
  'docs/spec/01-product.md',
  'docs/spec/01-produkt.md',
];

/// The product chapter below [root]; throws a [StateError] when none of [specCandidates]
/// exists.
File specFile(Directory root) {
  for (final candidate in specCandidates) {
    final file = File('${root.path}/$candidate');
    if (file.existsSync()) {
      return file;
    }
  }
  throw StateError(
    'no product chapter below ${root.path} (looked for $specCandidates)',
  );
}

final RegExp _marker = RegExp(
  r'^\s*(?:<!--)?\s*language-check: (off|on)\s*(?:-->)?\s*$',
);

List<String> _cells(String row) {
  final inner = row
      .trim()
      .replaceFirst(RegExp(r'^\|'), '')
      .replaceFirst(RegExp(r'\|$'), '');
  return inner.split('|').map((c) => c.trim()).toList();
}

List<String> _terms(String cell) => cell
    .replaceAll(RegExp(r'\s*\([^)]*\)'), '')
    .replaceAll('`', '')
    .split(',')
    .map((t) => t.trim())
    .where((t) => t.isNotEmpty)
    .toList();

/// Reads the term pairs from the Markdown text of the product chapter.
///
/// Takes the first table between the markers inside section 9, skips its header and
/// separator row, and splits the alternatives of a row into one pair each. A code cell with
/// one code applies to every alternative; an empty one gives null.
///
/// Throws a [FormatException] when section 9 has no marked table, a marker block does not
/// end, or a row has a different number of German and English alternatives.
List<TermPair> parse(String markdown) {
  final lines = markdown.split('\n');
  final section = lines.indexWhere((l) => l.startsWith('## 9.'));
  if (section < 0) {
    throw const FormatException('no section 9 in the product chapter');
  }
  var inside = false;
  var rows = <String>[];
  for (final line in lines.skip(section + 1)) {
    if (line.startsWith('## ')) {
      break;
    }
    final marker = _marker.firstMatch(line);
    if (marker != null) {
      if (marker.group(1) == 'off') {
        inside = true;
        rows = [];
        continue;
      }
      final closesTable = inside && rows.isNotEmpty;
      inside = false;
      if (closesTable) {
        break;
      }
      continue;
    }
    if (inside && line.trim().startsWith('|')) {
      rows.add(line);
    }
  }
  if (inside && rows.isNotEmpty) {
    throw const FormatException(
      'the term table of section 9 has no closing marker',
    );
  }
  if (rows.length < 3) {
    throw const FormatException(
      'no term table between the markers of section 9',
    );
  }
  final pairs = <TermPair>[];
  for (final row in rows.skip(2)) {
    final cells = _cells(row);
    final german = _terms(cells[0]);
    final english = _terms(cells.length > 1 ? cells[1] : '');
    final codes = _terms(cells.length > 2 ? cells[2] : '');
    if (german.length != english.length || german.isEmpty) {
      throw FormatException('German and English alternatives differ', row);
    }
    for (var i = 0; i < german.length; i++) {
      final code = codes.isEmpty
          ? null
          : (codes.length == german.length ? codes[i] : codes.first);
      pairs.add(TermPair(german[i], english[i], code));
    }
  }
  return pairs;
}

String _quote(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";

/// Renders [pairs] as the Dart source of lib/src/term_table.dart (formatted as `dart format`
/// leaves it).
String render(List<TermPair> pairs) {
  final out = StringBuffer()
    ..writeln('// SPDX-License-Identifier: Apache-2.0')
    ..writeln(
      '// GENERATED by tool/term_table.dart from the term table of the product chapter',
    )
    ..writeln(
      '// (docs/spec/01, section 9). Do not edit; run `dart run tool/term_table.dart`.',
    )
    ..writeln()
    ..writeln('/// The fixed terms of the apps in German and English.')
    ..writeln('library;')
    ..writeln()
    ..writeln("import 'term_pair.dart';")
    ..writeln()
    ..writeln(
      '/// The term table of docs/spec/01 section 9, one pair per alternative; German and',
    )
    ..writeln(
      '/// English texts use these terms for the same thing (test/term_table_test.dart).',
    )
    ..writeln('const List<TermPair> termTable = <TermPair>[')
    // The German terms are product strings (D-W-94): the markers keep them out of the
    // language gate of the repository.
    ..writeln('  // language-check: off');
  for (final p in pairs) {
    final code = p.code == null ? 'null' : _quote(p.code!);
    out.writeln(
      '  TermPair(${_quote(p.german)}, ${_quote(p.english)}, $code),',
    );
  }
  out
    ..writeln('  // language-check: on')
    ..writeln('];');
  return out.toString();
}

/// Writes lib/src/term_table.dart from the product chapter of the repository.
void main() {
  var dir = Directory.current.absolute;
  while (!Directory('${dir.path}/docs/spec').existsSync()) {
    if (dir.parent.path == dir.path) {
      stderr.writeln(
        'term_table: no repository root above ${Directory.current.path}',
      );
      exitCode = 1;
      return;
    }
    dir = dir.parent;
  }
  final pairs = parse(specFile(dir).readAsStringSync());
  File('${dir.path}/packages/l10n/lib/src/term_table.dart')
      .writeAsStringSync(render(pairs));
  stdout.writeln('term_table: ${pairs.length} pairs written');
}
