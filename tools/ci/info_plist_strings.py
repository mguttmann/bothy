"""Generate the localized permission texts of the iOS app from the ARB files (brief M5-07).

iOS shows the usage description of `Info.plist` when it asks for the microphone or the camera
(15 13, 15 14), and before the first Face ID check of the app lock (brief M5-08). The texts come from `packages/l10n` like every interface text (brief M5-07
requirement 8): `InfoPlist.strings` in `<lang>.lproj` of the runner holds one line per key and
language, and the English text is also the value in `Info.plist` itself, because iOS localizes
only keys that the plist has (and refuses the request of a key it lacks).

`KEYS` maps each plist key to its ARB message. The ARB texts are plain text without
placeholders, so a quote or a backslash is the only escape needed.

Usage:
    info_plist_strings.py [--root <repo>]            write the files
    info_plist_strings.py [--root <repo>] --check    fail (exit 1) when a file differs

Exit codes: 0 ok; 1 a file is stale, a message is missing or has placeholders; 2 usage error.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ARB_DIR = Path("packages/l10n/lib/l10n")
RUNNER = Path("apps/client/ios/Runner")
LANGUAGES = ("en", "de")

# Plist key -> ARB message (docs/decisions.d/M5-07.md D-M5-07-4).
KEYS: tuple[tuple[str, str], ...] = (
    ("NSCameraUsageDescription", "permissionCameraUsage"),
    ("NSMicrophoneUsageDescription", "permissionMicrophoneUsage"),
    ("NSPhotoLibraryUsageDescription", "permissionPhotoLibraryUsage"),
    ("NSFaceIDUsageDescription", "permissionFaceIdUsage"),
)

HEADER = (
    "/* SPDX-License-Identifier: Apache-2.0 */\n"
    "/* Generated by tools/ci/info_plist_strings.py from packages/l10n; do not edit. */\n"
)


class StringsError(Exception):
    """A message is missing or not plain text."""


def _escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def _messages(root: Path, language: str) -> dict[str, str]:
    path = root / ARB_DIR / f"app_{language}.arb"
    data = json.loads(path.read_text(encoding="utf-8"))
    out: dict[str, str] = {}
    for _, message in KEYS:
        text = data.get(message)
        if not isinstance(text, str) or not text:
            raise StringsError(f"{path}: message {message} is missing")
        if re.search(r"[{}]", text):
            raise StringsError(f"{path}: message {message} must be plain text")
        out[message] = text
    return out


def render(root: Path, language: str) -> str:
    """The content of `<language>.lproj/InfoPlist.strings`."""
    messages = _messages(root, language)
    lines = [f'"{key}" = "{_escape(messages[message])}";' for key, message in KEYS]
    return HEADER + "\n".join(lines) + "\n"


def plist_values(root: Path) -> dict[str, str]:
    """The English texts, which `Info.plist` must hold as its own values."""
    messages = _messages(root, "en")
    return {key: messages[message] for key, message in KEYS}


def _plist_value(plist: str, key: str) -> str | None:
    match = re.search(rf"<key>{re.escape(key)}</key>\s*<string>(.*?)</string>", plist, re.S)
    return None if match is None else match.group(1)


def check(root: Path) -> list[str]:
    """The problems of the checked-in files; empty when they equal a fresh generation."""
    problems: list[str] = []
    for language in LANGUAGES:
        path = root / RUNNER / f"{language}.lproj" / "InfoPlist.strings"
        want = render(root, language)
        if not path.is_file() or path.read_text(encoding="utf-8") != want:
            problems.append(f"{path} is stale: run python tools/ci/info_plist_strings.py")
    plist = (root / RUNNER / "Info.plist").read_text(encoding="utf-8")
    for key, text in plist_values(root).items():
        if _plist_value(plist, key) != text:
            problems.append(
                f"{RUNNER / 'Info.plist'}: {key} must be the English text of the ARB file"
            )
    return problems


def write(root: Path) -> None:
    """Writes the `InfoPlist.strings` files (the `Info.plist` values are kept by hand)."""
    for language in LANGUAGES:
        path = root / RUNNER / f"{language}.lproj" / "InfoPlist.strings"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(root, language), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    """Write (or with `--check` compare) the files; returns the exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.check:
            problems = check(args.root)
            for p in problems:
                print(p, file=sys.stderr)
            return 1 if problems else 0
        write(args.root)
        problems = check(args.root)
        for p in problems:
            print(p, file=sys.stderr)
        return 1 if problems else 0
    except StringsError as e:
        print(e, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
