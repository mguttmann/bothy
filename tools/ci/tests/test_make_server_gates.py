@pytest.mark.parametrize("shell", SHELLS, ids=["make-3.81", "make-4"])
def test_go_coverage_counts_production_code_only(fakes: Fakes, shell: list[str]) -> None:
    profile = COVERAGE.format(chat=18)
    (fakes.module / "coverage.out").write_text(profile, encoding="utf-8")
    command = _recipe_command("coverage", "'go-coverage'", fakes, "-o", "test")
    result = _bash(command, fakes, shell)
    # 20 of 22 production statements (90.9 %); with test/ and perf/ it would be 20 of 122.
