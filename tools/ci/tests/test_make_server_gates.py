def _executable(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    path.chmod(0o755)
    return path


@dataclass
class Fakes:
    """Recording fakes for the tools a server gate calls, and the throwaway module."""

    root: Path
    module: Path

    @property
    def bin(self) -> Path:
        return self.root / "bin"

    @property
    def pins(self) -> Path:
        return self.root / "pins"

    @property
    def log(self) -> Path:
        return self.root / "calls.jsonl"

    def calls(self, tool: str | None = None) -> list[dict[str, Any]]:
        if not self.log.exists():
            return []
        entries = [json.loads(line) for line in self.log.read_text().splitlines()]
        return [e for e in entries if tool is None or e["tool"] == tool]

    def env(self, **extra: str) -> dict[str, str]:
        env = {k: v for k, v in os.environ.items() if k not in _DROPPED}
        env["PATH"] = f"{self.bin}{os.pathsep}{env['PATH']}"
        env.update(FAKE_LOG=str(self.log), FAKE_PINS=str(self.pins), **extra)
        return env

    def make(
        self, *args: str, modules: str | None = None, **env: str
    ) -> subprocess.CompletedProcess[str]:
        """Run a target of the root Makefile with the fakes in place of the real tools."""
        variables = [
            f"GO_MODS={self.module if modules is None else modules}",
            "COMPONENTS=all",
            f"GO_PREREQS={self.bin / 'prereqs'}",
            f"FETCH={self.bin / 'fetch'}",
        ]
        return make(*args, *variables, env=self.env(**env))


def make(*args: str, env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    """Run make in the repository root; the test itself may run under `make test`."""
    if env is None:
        env = {k: v for k, v in os.environ.items() if k not in _DROPPED}
    return subprocess.run(
        ["make", "-s", "-C", str(REPO), *args],
        env=env,
        capture_output=True,
        text=True,
        check=False,
        timeout=300,
    )


@pytest.fixture
def fakes(tmp_path: Path) -> Fakes:
    root = tmp_path / "fakes"
    module = tmp_path / "svc"
    module.mkdir()
    (module / "go.mod").write_text("module example.com/svc\n\ngo 1.27\n", encoding="utf-8")
    fake = _FAKE.format(python=sys.executable)
    for name in ("prereqs", "fetch", "go", "go-arch-lint", "sqlc"):
        _executable(root / "bin" / name, fake)
    for name in ("go-arch-lint", "sqlc"):
        _executable(root / "pins" / name / name, fake)
    return Fakes(root, module)


def _git(repo: Path, *args: str) -> None:
    subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True)


def _commit_all(repo: Path) -> None:
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "config", "commit.gpgsign", "false")
    _git(repo, "config", "core.hooksPath", "/dev/null")
    _git(repo, "add", ".")
    _git(repo, "-c", "user.name=Test", "-c", "user.email=test@example.com", "commit", "-qm", "x")


def _recipe_command(
    target: str, marker: str, fakes: Fakes, *flags: str, modules: str | None = None
) -> str:
    """The shell command of `target` that contains `marker`, as `make -n` prints it.

    A command continues while its line ends with a backslash. GNU make 3.81 also keeps the
    recipe tab in front of a continuation line; 3.82 and later drop it, so the tab alone
    cannot mark a continuation.
    """
    printed = fakes.make("-n", *flags, target, modules=modules).stdout
    commands: list[str] = []
    for line in printed.splitlines():
        if commands and (commands[-1].endswith("\\") or line.startswith("\t")):
            commands[-1] += "\n" + line
        else:
            commands.append(line)
    [command] = [c for c in commands if marker in c]
    return command


# How a recipe line runs: GNU make 3.81 ignores .SHELLFLAGS (plain `bash -c`); make 3.82 and
# later, as in CI, use the Makefile's `-euo pipefail -c`.
SHELLS = [["bash", "-c"], ["bash", "-euo", "pipefail", "-c"]]


def _bash(
    command: str, fakes: Fakes, shell: list[str] = SHELLS[0], **env: str
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [*shell, command],
        cwd=REPO,
        env=fakes.env(**env),
        capture_output=True,
        text=True,
        check=False,
        timeout=120,
    )


@pytest.mark.parametrize("selection", [["COMPONENTS=apps"], ["GO_MODS=", "COMPONENTS=all"]])
def test_server_gates_skip_without_selected_go_module(selection: list[str]) -> None:
    result = make(*SERVER_GATES, *selection)
    assert result.returncode == 0, result.stdout + result.stderr
    skipped = _SKIP.findall(result.stdout)
    assert [name for name, _ in skipped] == SERVER_GATES
    assert {reason for _, reason in skipped} == {"no Go module selected under services/"}


def test_gates_contains_server_gates_but_not_perf() -> None:
    database = make("-pq", "gates").stdout  # -q: question mode, no recipe runs
    [line] = [x for x in database.splitlines() if x.startswith("gates:")]
    gates = line.split(":", 1)[1].split()
    order = ["fmt-check", "codegen-check", "lint", "typecheck", "arch", "migrations-lint"]
    order += ["test", "coverage"]
    assert [g for g in gates if g in order] == order
    assert "perf" not in gates
    assert "migrations-lock" not in gates


@pytest.mark.parametrize("gate", SERVER_GATES)
def test_missing_prerequisite_stops_the_gate_first(fakes: Fakes, gate: str) -> None:
    # Everything a gate would act on exists, so any step after the check would show up.
    (fakes.module / "migrations").mkdir()
    (fakes.module / "migrations" / "bad name.sql").write_text("x", encoding="utf-8")
    (fakes.module / ".go-arch-lint.yml").write_text("version: 3\n", encoding="utf-8")
    (fakes.module / "sqlc.yaml").write_text("version: '2'\n", encoding="utf-8")
    (fakes.module / "perf").mkdir()
    result = fakes.make(gate, FAKE_PREREQS_EXIT="1")
    assert result.returncode != 0
    assert f"{gate}: fake prerequisite missing" in result.stderr
    assert [(c["tool"], c["args"]) for c in fakes.calls()] == [("prereqs", [gate])]
    assert result.stdout == ""


