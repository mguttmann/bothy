"""Tests for the server gates of the root Makefile (codegen-check, arch, migrations-lint, perf).

Without a selected Go module every gate prints a SKIP line. The branches for a Go module
run the real recipes against a throwaway module: `GO_MODS` points at it, and `go`, `gofmt`,
go-arch-lint, golangci-lint, sqlc, OSV-Scanner, Semgrep (`SEMGREP`), the pin lookup (`FETCH`)
and the prerequisite check (`GO_PREREQS`) are replaced by recording fakes, so neither go,
docker nor the network is needed. Commands of other targets (`test`, `coverage`, `lint`,
`fmt-check`, `typecheck`, `osv`, `licenses`, `semgrep`) and some of the server gates are taken
from `make -n` (the targets would start this test suite again or run every other linter) and
run with bash, with and without errexit. Like the real `FETCH` (`uv run --project tools
...`), the fake is named by a path relative to the repository root, so a pin lookup that a
recipe runs after `cd` into a module fails here as it fails for real.
"""

