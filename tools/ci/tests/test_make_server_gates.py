# Fakes on PATH (or named by a make variable) and fakes of the pinned release binaries.
_ON_PATH = ("prereqs", "fetch", "go", "gofmt", "go-arch-lint", "golangci-lint", "sqlc", "semgrep")
_PINNED = ("go-arch-lint", "golangci-lint", "sqlc", "osv-scanner")


def _executable(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    path.chmod(0o755)
    return path


@dataclass
class Fakes:
    """Recording fakes for the tools a server gate calls, and the throwaway module."""

    root: Path
    module: Path

    @property
    def bin(self) -> Path:
        return self.root / "bin"

    @property
    def pins(self) -> Path:
        return self.root / "pins"

    @property
    def log(self) -> Path:
        return self.root / "calls.jsonl"

    def calls(self, tool: str | None = None) -> list[dict[str, Any]]:
        if not self.log.exists():
            return []
        entries = [json.loads(line) for line in self.log.read_text().splitlines()]
        return [e for e in entries if tool is None or e["tool"] == tool]

    def env(self, **extra: str) -> dict[str, str]:
        env = {k: v for k, v in os.environ.items() if k not in _DROPPED}
        env["PATH"] = f"{self.bin}{os.pathsep}{env['PATH']}"
        env.update(FAKE_LOG=str(self.log), FAKE_PINS=str(self.pins), **extra)
        return env

    def make(
        self, *args: str, modules: str | None = None, **env: str
    ) -> subprocess.CompletedProcess[str]:
        """Run a target of the root Makefile with the fakes in place of the real tools."""
        selected = str(self.module) if modules is None else modules
        variables = [
            f"GO_MODS={selected}",
            # The throwaway modules stand for modules with performance targets
            # (PERF_MODULES, docs/DECISIONS.md D-M2-38-3).
            f"PERF_MODULES={selected}",
            "COMPONENTS=all",
            f"GO_PREREQS={self.bin / 'prereqs'}",
            f"FETCH={os.path.relpath(self.bin / 'fetch', REPO)}",
        ]
        return make(*args, *variables, env=self.env(**env))


def make(*args: str, env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    """Run make in the repository root; the test itself may run under `make test`."""
    if env is None:
        env = {k: v for k, v in os.environ.items() if k not in _DROPPED}
    return subprocess.run(
        ["make", "-s", "-C", str(REPO), *args],
        env=env,
        capture_output=True,
        text=True,
        check=False,
        timeout=300,
    )


@pytest.fixture
def fakes(tmp_path: Path) -> Fakes:
    root = tmp_path / "fakes"
    module = tmp_path / "svc"
    module.mkdir()
    (module / "go.mod").write_text("module example.com/svc\n\ngo 1.27\n", encoding="utf-8")
    fake = _FAKE.format(python=sys.executable)
    for name in _ON_PATH:
        _executable(root / "bin" / name, fake)
    for name in _PINNED:
        _executable(root / "pins" / name / name, fake)
    return Fakes(root, module)


def _commit_all(repo: Path) -> None:
    init_repo(repo)
    commit(repo, "x")


def _recipe_command(
    target: str, marker: str, fakes: Fakes, *flags: str, modules: str | None = None
) -> str:
    """The shell command of `target` that contains `marker`, as `make -n` prints it.

    A command continues while its line ends with a backslash. GNU make 3.81 also keeps the
    recipe tab in front of a continuation line; 3.82 and later drop it, so the tab alone
    cannot mark a continuation.
    """
    printed = fakes.make("-n", *flags, target, modules=modules).stdout
    commands: list[str] = []
    for line in printed.splitlines():
        if commands and (commands[-1].endswith("\\") or line.startswith("\t")):
            commands[-1] += "\n" + line
        else:
            commands.append(line)
    [command] = [c for c in commands if marker in c]
    return command


# How a recipe line runs. Every GNU make runs the Makefile's recipes with `bash -euo pipefail`
# (make 3.81 ignores .SHELLFLAGS, so SHELL carries the flags there; test_make_shell.py). The
# plain `bash -c` case stays: it proves that each recipe also stops on its own, with an explicit
# `|| exit 1` after every step (docs/DECISIONS.md M1-01/8).
SHELLS = [["bash", "-c"], ["bash", "-euo", "pipefail", "-c"]]
SHELL_IDS = ["plain-bash", "errexit"]


def _bash(
    command: str, fakes: Fakes, shell: list[str] = SHELLS[0], **env: str
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [*shell, command],
        cwd=REPO,
        env=fakes.env(**env),
        capture_output=True,
        text=True,
        check=False,
        timeout=120,
    )


