@pytest.mark.parametrize("shell", SHELLS, ids=["make-3.81", "make-4"])
def test_go_coverage_stops_and_removes_its_copy_when_go_tool_cover_fails(
    fakes: Fakes, shell: list[str], tmp_path: Path
) -> None:
    """A failing `go tool cover` ends the gate at that step, also without pipefail (make 3.81)
    and even with a threshold of 0; the filtered copy in TMPDIR is gone afterwards."""
    scratch = tmp_path / "scratch"
    scratch.mkdir()
    (fakes.module / "coverage.out").write_text(COVERAGE.format(chat=18), encoding="utf-8")
    command = _recipe_command("coverage", "'go-coverage'", fakes, "-o", "test", "COVERAGE_GO_MIN=0")
    result = _bash(command, fakes, shell, TMPDIR=str(scratch), FAKE_COVER_EXIT="1")
    assert result.returncode != 0
    assert "printed no total" not in result.stderr  # stopped at go tool cover itself
    [cover] = fakes.calls("go")
    assert Path(cover["args"][2].removeprefix("-func=")).parent == scratch
    assert list(scratch.iterdir()) == []


