def test_codegen_check_runs_sqlc_and_go_generate(fakes: Fakes) -> None:
    (fakes.module / "sqlc.yaml").write_text("version: '2'\n", encoding="utf-8")
    _commit_all(fakes.module)
    result = fakes.make("codegen-check")
    assert result.returncode == 0, result.stdout + result.stderr
    module = str(fakes.module.resolve())
    [sqlc] = fakes.calls("sqlc")
    assert (sqlc["args"], sqlc["cwd"]) == (["generate", "-f", "sqlc.yaml"], module)
    assert sqlc["exe"] == str(fakes.pins / "sqlc" / "sqlc")
    [go] = fakes.calls("go")
    assert (go["args"], go["cwd"]) == (["generate", "./..."], module)
    # //go:generate directives call the tools by name: the pinned ones must win over others
    # on PATH (the fakes directory holds decoys of both).
    for tool in ("go-arch-lint", "sqlc"):
        first = next(d for d in go["path"].split(os.pathsep) if (Path(d) / tool).is_file())
        assert first == str(fakes.pins / tool)


