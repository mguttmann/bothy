def test_migrations_lint_checks_the_module(fakes: Fakes) -> None:
    migrations = fakes.module / "migrations"
    migrations.mkdir()
    sql = migrations / "00001_init.sql"
    sql.write_text("-- +goose Up\nCREATE TABLE t (id int);\n", encoding="utf-8")
    sum_line = f"{hashlib.sha256(sql.read_bytes()).hexdigest()}  00001_init.sql\n"
    (fakes.module / "migrations.sha256").write_text(sum_line, encoding="utf-8")
    assert fakes.make("migrations-lint").returncode == 0
    (migrations / "00002_users.sql").write_text("-- +goose Up\nSELECT 1;\n", encoding="utf-8")
    result = fakes.make("migrations-lint")
    assert result.returncode != 0
    assert "00002_users.sql: unlocked-migration:" in result.stdout


