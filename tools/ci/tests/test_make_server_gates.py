"""Tests for the server gates of the root Makefile (codegen-check, arch, migrations-lint, perf).

Without a selected Go module every gate prints a SKIP line. The branches for a Go module
run the real recipes against a throwaway module: `GO_MODS` points at it, and `go`,
go-arch-lint, sqlc, the pin lookup (`FETCH`) and the prerequisite check (`GO_PREREQS`) are
replaced by recording fakes, so neither go, docker nor the network is needed. The Go
branches of `test` and `coverage` are taken from `make -n` (the targets would start this
test suite again) and run with bash.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pytest

REPO = Path(__file__).resolve().parents[3]
SERVER_GATES = ["codegen-check", "arch", "migrations-lint", "perf"]
_SKIP = re.compile(r"^\s*SKIP\s+(\S+)\s+(.*)$", re.MULTILINE)
# The test may run under `make test` (MAKEFLAGS, MAKELEVEL) and in a shell or CI job that sets
# configuration the Makefile reads with `?=`; neither may leak into the make runs below.
_DROPPED = {"MAKEFLAGS", "MAKELEVEL", "MFLAGS", "COMPONENTS", "COVERAGE_GO_MIN", "PERF_TIMEOUT"}

