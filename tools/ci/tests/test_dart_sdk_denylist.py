"""Tests for dart_sdk_denylist: no Dart package depends on an OpenTelemetry or analytics SDK.

ADR 0057 "Confirmation" and brief M4-31 Design note 6: the gate reads the root `pubspec.lock`
and fails for a package whose name matches a deny pattern; `sentry_flutter` (crash reports,
15 16) and its own Dart core `sentry` are the exception.
"""

from __future__ import annotations

from pathlib import Path

import dart_sdk_denylist as dl
import pytest

REPO = Path(__file__).resolve().parents[3]

LOCK = """# Generated by pub
# See https://dart.dev/tools/pub/glossary#lockfile
packages:
{packages}sdks:
  dart: ">=3.13.5 <4.0.0"
"""

ENTRY = """  {name}:
    dependency: transitive
    description:
      name: {name}
      sha256: "00"
      url: "https://pub.dev"
    source: hosted
    version: "1.0.0"
"""


def _lock(tmp_path: Path, *names: str) -> Path:
    path = tmp_path / "pubspec.lock"
    path.write_text(
        LOCK.format(packages="".join(ENTRY.format(name=n) for n in names)), encoding="utf-8"
    )
    return path


def test_denied_packages_are_reported(tmp_path: Path) -> None:
    lock = _lock(
        tmp_path,
        "dio",
        "opentelemetry_api",
        "firebase_analytics",
        "mixpanel_flutter",
        "sentry_flutter",
    )
    assert dl.findings(lock) == [
        "firebase_analytics: matches the deny pattern firebase_analytics",
        "mixpanel_flutter: matches the deny pattern mixpanel*",
        "opentelemetry_api: matches the deny pattern opentelemetry*",
    ]
    assert dl.main(["--lock", str(lock)]) == 1


def test_only_sentry_passes(tmp_path: Path) -> None:
    lock = _lock(tmp_path, "sentry_flutter", "sentry", "dio", "flutter_riverpod")
    assert dl.findings(lock) == []
    assert dl.main(["--lock", str(lock)]) == 0


@pytest.mark.parametrize(
    "name",
    [
        "amplitude_flutter",
        "segment_analytics",
        "posthog_flutter",
        "datadog_flutter_plugin",
        "newrelic_mobile",
        "appcenter_analytics",
        "opentelemetry",
    ],
)
def test_every_pattern_has_a_package_it_catches(tmp_path: Path, name: str) -> None:
    assert len(dl.findings(_lock(tmp_path, name))) == 1


def test_exemptions_match_no_pattern_by_accident() -> None:
    # The exemption exists for the crash path of 15 16; it must stay narrow.
    assert frozenset({"sentry_flutter", "sentry"}) == dl.EXEMPT


def test_unreadable_lock_is_a_usage_error(tmp_path: Path) -> None:
    assert dl.main(["--lock", str(tmp_path / "missing.lock")]) == 2
    bad = tmp_path / "pubspec.lock"
    bad.write_text("packages: [1, 2]\n", encoding="utf-8")
    assert dl.main(["--lock", str(bad)]) == 2


def test_repository_lock_passes() -> None:
    assert dl.findings(REPO / "pubspec.lock") == []
