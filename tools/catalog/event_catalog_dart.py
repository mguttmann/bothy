"""Generate the client's event catalogue (`packages/domain`) from `docs/spec/actions.yaml`.

The domain package decides with the catalogue whether an event type carries
`resource.version` (docs/spec/04 section 9 item 3) and whether it is durable or personal.
`action_catalog.py` has no output hook for Dart, so this small script reads the `events:` list
itself (docs/DECISIONS.md D-M4-08-3); `action_catalog.py check` stays the gate for the
catalogue's own rules.

Usage:
    event_catalog_dart.py [--root <repo>]            write OUTPUT (the generated Dart part)
    event_catalog_dart.py [--root <repo>] --check    fail (exit 1) when OUTPUT is stale

Exit codes: 0 ok; 1 the catalogue cannot be read or (with `--check`) the file is stale; 2 usage
error.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

CATALOGUE = Path("docs/spec/actions.yaml")
OUTPUT = Path("packages/domain/lib/src/rules/event_catalog.g.dart")
_TYPE = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$")
_RESOURCE = re.compile(r"^[a-z][a-z0-9_]*")


class CatalogueError(Exception):
    """The catalogue does not yield a valid event table; the message names the entry."""


@dataclass(frozen=True)
class EventEntry:
    """One event type of the client catalogue.

    Attributes:
        type: the event type, for example `message.created`.
        durable: `kind: durable` (else ephemeral).
        carries_resource_version: `resource_version: true`.
        resource_kind: the leading word of `resource` (`message`, `thread`, ...).
        personal: `audience: self`.
    """

    type: str
    durable: bool
    carries_resource_version: bool
    resource_kind: str
    personal: bool


def events(text: str) -> list[EventEntry]:
    """Read the `events:` list of the catalogue.

    Args:
        text: the YAML text of `docs/spec/actions.yaml`.

    Returns:
        The entries sorted by type.

    Raises:
        CatalogueError: the list is missing, an entry lacks `type`, `kind`, `resource` or
            `resource_version`, has a value of the wrong kind, or a type appears twice.
    """
    data = yaml.safe_load(text)
    items = data.get("events") if isinstance(data, dict) else None
    if not isinstance(items, list):
        raise CatalogueError("actions.yaml: no `events:` list")
    found: dict[str, EventEntry] = {}
    for index, item in enumerate(items):
        if not isinstance(item, dict):
            raise CatalogueError(f"events[{index}]: not a mapping")
        kind_type = item.get("type")
        if not isinstance(kind_type, str) or not _TYPE.match(kind_type):
            raise CatalogueError(f"events[{index}]: invalid or missing type")
        kind = item.get("kind")
        version = item.get("resource_version")
        resource = item.get("resource")
        if kind not in ("durable", "ephemeral"):
            raise CatalogueError(f"{kind_type}: kind must be durable or ephemeral")
        if not isinstance(version, bool):
            raise CatalogueError(f"{kind_type}: resource_version must be true or false")
        match = _RESOURCE.match(resource) if isinstance(resource, str) else None
        if match is None:
            raise CatalogueError(f"{kind_type}: resource is missing")
        if kind_type in found:
            raise CatalogueError(f"{kind_type}: appears twice")
        found[kind_type] = EventEntry(
            kind_type, kind == "durable", version, match.group(0), item.get("audience") == "self"
        )
    return [found[t] for t in sorted(found)]


def render(table: list[EventEntry]) -> str:
    """Render the Dart library part with the event table.

    Args:
        table: the entries from `events`.

    Returns:
        The content of `event_catalog.g.dart`.
    """
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// GENERATED by tools/catalog/event_catalog_dart.py from docs/spec/actions.yaml.",
        "// Do not edit; run `make event-catalog` (make codegen-check holds this file).",
        "",
        "part of 'event_catalog.dart';",
        "",
        "const Map<String, EventInfo> _catalogue = <String, EventInfo>{",
    ]
    for e in table:
        out.append(
            f"  '{e.type}': EventInfo(type: '{e.type}', durable: {str(e.durable).lower()}, "
            f"carriesResourceVersion: {str(e.carries_resource_version).lower()}, "
            f"resourceKind: '{e.resource_kind}', personal: {str(e.personal).lower()}),"
        )
    out += ["};", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    """Command line entry point; see the module docstring for usage and exit codes."""
    parser = argparse.ArgumentParser(prog="event_catalog_dart.py")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:  # argparse ends on usage errors (2) and on --help (0)
        return exc.code if isinstance(exc.code, int) else 2
    root: Path = args.root
    try:
        text = render(events((root / CATALOGUE).read_text(encoding="utf-8")))
    except (OSError, yaml.YAMLError, CatalogueError) as exc:
        print(f"event-catalog: {exc}", file=sys.stderr)
        return 1
    target = root / OUTPUT
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current != text:
            print(
                f"event-catalog: {OUTPUT} is stale; run `make event-catalog` and commit the result",
                file=sys.stderr,
            )
            return 1
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
