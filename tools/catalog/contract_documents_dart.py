"""Embed the documents the fake server of sync_engine reads in the fake itself.

The fake server of M4-17 validates every request, response and frame against the API
documents `docs/api/openapi.yaml` and `docs/api/asyncapi.yaml`, since M4-26 takes the step-up
of each action from `docs/spec/actions.yaml`, and since M4-27 answers the grant preview with
the example of `docs/spec/07-permissions.md` 9.3. The app's integration tests run it
inside the app, and on macOS the app sandbox cannot read the repository, so the fake carries
a gzip and base64 copy of these documents (`ContractSchemas.embedded`,
`ActionCatalog.embedded`, `grantPreviewExample`; docs/DECISIONS.md D-M4-18-17, D-M4-26-9,
D-M4-27-7). The copy is test code only: it lives in `package:sync_engine/testing.dart`, which
no release build imports (tools/arch-check rule 10).

Usage:
    contract_documents_dart.py [--root <repo>]            write OUTPUT (the generated Dart part)
    contract_documents_dart.py [--root <repo>] --check    fail (exit 1) when OUTPUT is stale

`--check` decodes the copy and compares the text, so a different zlib build gives no false
finding. Exit codes: 0 ok; 1 a document cannot be read or (with `--check`) the file is stale;
2 usage error.
"""

from __future__ import annotations

import argparse
import base64
import binascii
import gzip
import re
import sys
import zlib
from pathlib import Path

OPENAPI = Path("docs/api/openapi.yaml")
ASYNCAPI = Path("docs/api/asyncapi.yaml")
ACTIONS = Path("docs/spec/actions.yaml")
PERMISSIONS = Path("docs/spec/07-permissions.md")
SOURCES = (OPENAPI, ASYNCAPI, ACTIONS, PERMISSIONS)
OUTPUT = Path("packages/sync_engine/lib/src/testing/contract_documents.g.dart")
_CHUNK = 76
_LISTS = ("_openapiGzip", "_asyncapiGzip", "_actionsGzip", "_permissionsGzip")


class EmbeddedError(Exception):
    """The generated file does not hold a readable copy; the message names the list."""


def _chunks(text: str) -> list[str]:
    data = base64.b64encode(gzip.compress(text.encode("utf-8"), compresslevel=9, mtime=0))
    encoded = data.decode("ascii")
    return [encoded[i : i + _CHUNK] for i in range(0, len(encoded), _CHUNK)]


def render(*texts: str) -> str:
    """Render the Dart library part with the documents.

    Args:
        texts: the texts of the documents of SOURCES, in that order.

    Returns:
        The content of `contract_documents.g.dart`.
    """
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// GENERATED by tools/catalog/contract_documents_dart.py from docs/api/openapi.yaml,",
        "// docs/api/asyncapi.yaml, docs/spec/actions.yaml and docs/spec/07-permissions.md. Do",
        "// not edit; run `make contract-documents` (make codegen-check holds this file).",
        "",
        "part of 'schema_validator.dart';",
    ]
    for name, text in zip(_LISTS, texts, strict=True):
        out += ["", f"const List<String> {name} = <String>["]
        out += [f"  '{chunk}'," for chunk in _chunks(text)]
        out.append("];")
    out.append("")
    return "\n".join(out)


def embedded(source: str) -> tuple[str, ...]:
    """Decode the documents of a generated file.

    Args:
        source: the content of `contract_documents.g.dart`.

    Returns:
        The texts of the documents of SOURCES, in that order.

    Raises:
        EmbeddedError: a list is missing or does not decode.
    """
    texts: list[str] = []
    for name in _LISTS:
        match = re.search(rf"const List<String> {name} = <String>\[(.*?)\];", source, re.S)
        if match is None:
            raise EmbeddedError(f"no list {name}")
        data = "".join(re.findall(r"'([A-Za-z0-9+/=]*)'", match.group(1)))
        try:
            texts.append(gzip.decompress(base64.b64decode(data)).decode("utf-8"))
        except (binascii.Error, OSError, EOFError, zlib.error, UnicodeDecodeError) as exc:
            raise EmbeddedError(f"{name} does not decode: {exc}") from exc
    return tuple(texts)


def main(argv: list[str] | None = None) -> int:
    """Command line entry point; see the module docstring for usage and exit codes."""
    parser = argparse.ArgumentParser(prog="contract_documents_dart.py")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:  # argparse ends on usage errors (2) and on --help (0)
        return exc.code if isinstance(exc.code, int) else 2
    root: Path = args.root
    try:
        texts = tuple((root / source).read_text(encoding="utf-8") for source in SOURCES)
    except OSError as exc:
        print(f"contract-documents: {exc}", file=sys.stderr)
        return 1
    target = root / OUTPUT
    if args.check:
        try:
            current = embedded(target.read_text(encoding="utf-8")) if target.is_file() else None
        except EmbeddedError:
            current = None
        if current != texts:
            print(
                f"contract-documents: {OUTPUT} is stale; run `make contract-documents` and commit"
                " the result",
                file=sys.stderr,
            )
            return 1
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(*texts), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
