import tempfile
import unittest
from pathlib import Path

import tokens
from tokenkit import dtcg, emit_ts, model

ROOT = Path(__file__).resolve().parents[3]
TSC = ROOT / "sdk" / "typescript" / "node_modules" / ".bin" / "tsc"


def _object(text: str, name: str):
    """The literal of `export const <name> = {...} as const` as JSON data (keys quoted, trailing commas dropped)."""
    match = re.search(rf"^export const {name} = (\{{.*?^\}}) as const", text, re.S | re.M)
    if match is None:
        raise AssertionError(f"no export const {name}")
    body = re.sub(r"(^\s*|\{ |, )([A-Za-z_$][\w$]*|\d+):", r'\1"\2":', match.group(1), flags=re.M)
    body = re.sub(r",(\s*[}\]])", r"\1", body)
    return json.loads(body)


def _at(tree, keys):
    for key in keys:
        tree = tree[key]
    return tree


def _tsc_args(path: Path) -> list[str]:
    return [str(TSC), *emit_ts.TSC_FLAGS, str(path)]


class EmitTsTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.model = model.build(tokens.RESOLVER)
        outputs, _ = tokens.generate()
        cls.text = outputs[tokens.BUILD / "ts" / "tokens.gen.ts"]
        cls.resolved = json.loads(outputs[tokens.BUILD / "tokens.resolved.json"])

    def test_role_names_map_to_typescript_keys(self):
        self.assertEqual(emit_ts.ts_path("color.accent.bg-hover"), ["accent", "bgHover"])
        self.assertEqual(emit_ts.ts_path("color.viz.series.1"), ["viz", "series", "1"])
        self.assertEqual(emit_ts.ts_path("color.text.on-sidebar-muted"), ["text", "onSidebarMuted"])
        self.assertEqual(emit_ts.ts_path("color.scrim"), ["scrim"])
        self.assertEqual(emit_ts.ts_path("color.viz.area-fill"), ["viz", "areaFill"])

    def test_invalid_key_is_an_error(self):
        with self.assertRaises(ValueError):
            emit_ts.ts_path("color.a b")

    def test_every_color_role_of_both_themes_with_the_resolved_value(self):
        for theme in ("light", "dark"):
            data = _object(self.text, theme)
            roles = {p: t for p, t in self.resolved["contexts"]["theme"][theme].items() if t["type"] == "color"}
            self.assertGreater(len(roles), 100)
            for path, token in roles.items():
                with self.subTest(theme=theme, role=path):
                    value = token["value"]
                    expected = value if isinstance(value, str) else {"hex": value["hex"], "alpha": value["alpha"]}
                    self.assertEqual(_at(data, emit_ts.ts_path(path)), expected)
            self.assertEqual(_count_leaves(data), len(roles))

    def test_chart_and_state_roles_present(self):
        for theme in ("light", "dark"):
            data = _object(self.text, theme)
            self.assertEqual(sorted(data["viz"]["series"]), [str(i) for i in range(1, 9)])
            for key in ("grid", "axis", "areaFill"):
                self.assertIn(key, data["viz"])
            for state in ("success", "warning", "danger"):
                self.assertIn("fg", data[state])

    def test_same_roles_as_the_dart_colors(self):
        dart_fields = [p for p, t in next(iter(self.model.contexts["theme"].values())).items() if t.type == "color"]
        data = _object(self.text, "light")
        for path in dart_fields:
            _at(data, emit_ts.ts_path(path))

    def test_fonts_sizes_and_radii(self):
        base = self.resolved["base"]
        fonts = _object(self.text, "fonts")
        self.assertEqual(fonts["sans"], base["font.family.sans"]["value"])
        self.assertEqual(fonts["mono"], base["font.family.mono"]["value"])
        sizes = _object(self.text, "sizes")
        expected_sizes = {p.split(".")[-1]: t["value"]["value"] for p, t in base.items() if p.startswith("font.size.")}
        self.assertEqual(sizes, expected_sizes)
        radii = _object(self.text, "radii")
        expected_radii = {p.split(".")[-1]: t["value"]["value"] for p, t in base.items() if p.startswith("radius.")}
        self.assertEqual(radii, expected_radii)

    def test_generated_header(self):
        head = self.text.splitlines()[:3]
        self.assertEqual(head[0], "// SPDX-License-Identifier: Apache-2.0")
        self.assertTrue(any("Generated by tools/design-tokens/tokens.py" in line for line in head), head)
        self.assertTrue(any("Do not edit" in line for line in head), head)

    def test_theme_type_and_no_imports(self):
        self.assertIn("export type Theme = Widen<typeof light>;", self.text)
        self.assertRegex(self.text, r"(?m)^\} as const satisfies Theme;$")
        self.assertNotRegex(self.text, r"(?m)^import ")

    def test_deterministic(self):
        self.assertEqual(emit_ts.render(self.model), emit_ts.render(self.model))
        self.assertEqual(emit_ts.render(model.build(tokens.RESOLVER)), self.text)

    def test_no_dashes_outside_ascii_hyphen(self):
        self.assertNotRegex(self.text, r"[\u2013\u2014]")

    def test_role_that_is_also_a_group_is_an_error(self):
        black = {"colorSpace": "srgb", "components": [0, 0, 0]}
        token = dtcg.Token(path="color.a", value=black, type="color", hex="#000000")
        with self.assertRaises(ValueError):
            emit_ts.color_tree({"color.a": token, "color.a.b": token})


def _count_leaves(tree) -> int:
    if isinstance(tree, dict) and set(tree) != {"hex", "alpha"}:
        return sum(_count_leaves(v) for v in tree.values())
    return 1


@unittest.skipUnless(TSC.exists(), "tsc of sdk/typescript not installed (make bootstrap); make tokens runs it")
class CompileTest(unittest.TestCase):
    """`tsc --strict --noEmit` accepts the generated file and rejects a dark theme that lost a role."""

    @classmethod
    def setUpClass(cls):
        cls.text = emit_ts.render(model.build(tokens.RESOLVER))

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(prefix="design-tokens-tsc-")
        self.dir = Path(self._tmp.name)

    def tearDown(self):
        self._tmp.cleanup()

    def _compile(self, text: str):
        path = self.dir / "tokens.gen.ts"
        path.write_text(text, encoding="utf-8")
        return subprocess.run(_tsc_args(path), capture_output=True, text=True, check=False, cwd=self.dir)

    def test_generated_file_compiles(self):
        proc = self._compile(self.text)
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)

    def test_dark_without_a_role_does_not_compile(self):
        head, sep, dark = self.text.partition("export const dark = {")
        self.assertTrue(sep)
        dark = re.sub(r'(?m)^\s*grid: "#[0-9a-f]{6}",\n', "", dark, count=1)
        proc = self._compile(head + sep + dark)
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("grid", proc.stdout)


class FontFilesTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(prefix="design-tokens-fonts-")
        self.dir = Path(self._tmp.name)
        self.vendor = self.dir / "vendor"
        self.target = self.dir / "fonts"
        shutil.copytree(tokens.VENDOR / "fonts", self.vendor)

    def tearDown(self):
        self._tmp.cleanup()

    def test_copies_are_every_vendor_font_and_license(self):
        copies = emit_ts.font_copies(self.vendor, self.target)
        names = sorted(p.name for p in copies)
        self.assertEqual(names, sorted(p.name for p in self.vendor.iterdir()))
        self.assertIn("atkinson-hyperlegible-next.OFL.txt", names)
        self.assertIn("atkinson-hyperlegible-mono.OFL.txt", names)

    def test_problems_name_missing_changed_and_extra_files(self):
        copies = emit_ts.font_copies(self.vendor, self.target)
        self.target.mkdir()
        for dst, src in copies.items():
            shutil.copyfile(src, dst)
        self.assertEqual(emit_ts.font_problems(copies, self.target), [])
        (self.target / "atkinson-hyperlegible-next.OFL.txt").unlink()
        (self.target / "atkinson-hyperlegible-mono-latin-wght-normal.woff2").write_bytes(b"x")
        (self.target / "extra.woff2").write_bytes(b"x")
        self.assertEqual(
            emit_ts.font_problems(copies, self.target),
            [
                self.target / "atkinson-hyperlegible-mono-latin-wght-normal.woff2",
                self.target / "atkinson-hyperlegible-next.OFL.txt",
                self.target / "extra.woff2",
            ],
        )

    def test_font_without_its_license_is_an_error(self):
        (self.vendor / "atkinson-hyperlegible-mono.OFL.txt").unlink()
        with self.assertRaises(ValueError):
            emit_ts.font_copies(self.vendor, self.target)


if __name__ == "__main__":
    unittest.main()
