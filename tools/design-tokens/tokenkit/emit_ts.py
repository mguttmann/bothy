"""TypeScript constants for web consumers of the design tokens (`design/build/ts/tokens.gen.ts`).

The file holds the colour roles of both themes (`light`, `dark`), the font families, the font
sizes and the radii as plain TypeScript without imports, so that the Grafana panel plugin can
import it without a runtime dependency (docs/spec/25-visualization.md section 10 item 3). The
font files it names are copied next to it, with their licence, by `font_copies`.

Name mapping (docs/DECISIONS.md D-M7-24-1): a colour role `color.<a>.<b>` becomes the nested key
path `<a>.<b>` below the theme object; a segment with hyphens or underscores becomes camelCase
(`bg-hover` to `bgHover`), a numeric segment stays a numeric key (`viz.series[1]`). Font families,
sizes and radii keep the last segment of their path (`font.family.sans` to `fonts.sans`,
`font.size.12` to `sizes[12]`, `radius.md` to `radii.md`).
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from . import dtcg
from .model import Model

HEADER = "Generated by tools/design-tokens/tokens.py from design/tokens. Do not edit; change the source and regenerate."
# Flags of the compile check (`make tokens`, target `ts` of tools/design-tokens/Makefile).
TSC_FLAGS = ("--strict", "--noEmit", "--target", "es2022", "--module", "es2022", "--lib", "es2022")

_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _key(segment: str, path: str) -> str:
    if segment.isdigit():
        return str(int(segment))
    words = [w for w in re.split(r"[-_]", segment) if w]
    key = (words[0] + "".join(w[:1].upper() + w[1:] for w in words[1:])) if words else ""
    if not _IDENT.match(key):
        raise ValueError(f"no TypeScript key for segment {segment!r} of {path}")
    return key


def ts_path(path: str, drop: str = "color") -> list[str]:
    """TypeScript key path of a token path.

    Args:
        path: dotted token path, for example `color.accent.bg-hover`.
        drop: leading segment that the enclosing object already names.

    Returns:
        The keys, for example `["accent", "bgHover"]`; `$root` segments are left out.

    Raises:
        ValueError: a segment gives no valid TypeScript identifier or numeric key.

    Example:
        >>> ts_path("color.viz.series.1")
        ['viz', 'series', '1']
    """
    parts = [p for p in path.split(".") if p != "$root"]
    if parts and parts[0] == drop:
        parts = parts[1:]
    if not parts:
        raise ValueError(f"no TypeScript key for {path}")
    return [_key(p, path) for p in parts]


def _color_value(token: dtcg.Token) -> str | dict:
    # As in tokens.resolved.json: a hex string, or hex and alpha for a translucent colour.
    alpha = dtcg.color_alpha(token.value)
    return token.hex if alpha >= 1 else {"hex": token.hex, "alpha": alpha}


def color_tree(tokens: dict[str, dtcg.Token]) -> dict:
    """Nested object of the colour roles of one theme context.

    Args:
        tokens: path -> token of the context; tokens that are not colours are skipped.

    Returns:
        Nested dict keyed by `ts_path`, leaves as in `tokens.resolved.json`.

    Raises:
        ValueError: two roles map to the same key, or a role is also a group of other roles.
    """
    tree: dict = {}
    for path in sorted(tokens):
        token = tokens[path]
        if token.type != "color":
            continue
        *groups, leaf = ts_path(path)
        node = tree
        for key in groups:
            child = node.setdefault(key, {})
            if not isinstance(child, dict) or _is_leaf(child):
                raise ValueError(f"{path}: {key} is a colour role and a group")
            node = child
        if leaf in node:
            raise ValueError(f"{path}: key {leaf} is used twice")
        node[leaf] = _color_value(token)
    return tree


def _is_leaf(value) -> bool:
    return not isinstance(value, dict) or (set(value) == {"hex", "alpha"} and not isinstance(value["hex"], dict))


def _number(value: float) -> str:
    value = float(value)
    return str(int(value)) if value.is_integer() else repr(value)


def _px(dim: dict) -> float:
    return dim["value"] * 16 if dim["unit"] == "rem" else dim["value"]


def _literal(value, indent: int) -> str:
    pad = "  " * (indent + 1)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, bool):
        raise ValueError("booleans are not emitted")
    if isinstance(value, (int, float)):
        return _number(value)
    if isinstance(value, list):
        return "[" + ", ".join(_literal(v, indent) for v in value) + "]"
    if set(value) == {"hex", "alpha"}:
        return f"{{ hex: {json.dumps(value['hex'])}, alpha: {_number(value['alpha'])} }}"
    lines = [f"{pad}{key}: {_literal(value[key], indent + 1)}," for key in value]
    return "{\n" + "\n".join(lines) + "\n" + "  " * indent + "}"


def _group(base: dict[str, dtcg.Token], prefix: str, value) -> dict:
    return {
        _key(p.split(".")[-1], p): value(t)
        for p, t in sorted(base.items(), key=lambda kv: _sort_key(kv[0]))
        if p.startswith(prefix)
    }


def _sort_key(path: str):
    tail = path.split(".")[-1]
    return (0, int(tail), "") if tail.isdigit() else (1, 0, tail)


def render(model: Model) -> str:
    """The file `tokens.gen.ts`.

    Args:
        model: the token model of `model.build`; needs the theme contexts `light` and `dark`.

    Returns:
        TypeScript source: `light` and `dark` (colour roles), the type `Theme`, `fonts`, `sizes`
        (font sizes in px) and `radii` (px), every object `as const`.

    Raises:
        ValueError: a theme is missing or a role has no TypeScript key.
    """
    themes = model.contexts.get("theme", {})
    if sorted(themes) != ["dark", "light"]:
        raise ValueError(f"tokens.gen.ts needs the themes light and dark, got {sorted(themes)}")
    base = model.base
    fonts = _group(base, "font.family.", lambda t: t.value if isinstance(t.value, list) else [t.value])
    sizes = _group(base, "font.size.", lambda t: _px(t.value))
    radii = _group(base, "radius.", lambda t: _px(t.value))
    parts = [
        "// SPDX-License-Identifier: Apache-2.0",
        f"// {HEADER}",
        "",
        "/** Colour roles of the light theme; keys follow the roles (`color.accent.bg-hover` is `accent.bgHover`). */",
        f"export const light = {_literal(color_tree(themes['light']), 0)} as const;",
        "",
        "/** Widens literal types to their base types, so that both themes share one shape. */",
        "type Widen<T> = T extends string",
        "  ? string",
        "  : T extends number",
        "    ? number",
        "    : { readonly [K in keyof T]: Widen<T[K]> };",
        "",
        "/** Shape of a theme: every colour role of `light`; `dark` must have exactly the same roles. */",
        "export type Theme = Widen<typeof light>;",
        "",
        "/** Colour roles of the dark theme, same keys as `light`. */",
        f"export const dark = {_literal(color_tree(themes['dark']), 0)} as const satisfies Theme;",
        "",
        "/** Font families with their fallback list, first entry is the bundled font (see fonts/). */",
        f"export const fonts = {_literal(fonts, 0)} as const;",
        "",
        "/** Font sizes in px, keyed by their size. */",
        f"export const sizes = {_literal(sizes, 0)} as const;",
        "",
        "/** Corner radii in px. */",
        f"export const radii = {_literal(radii, 0)} as const;",
    ]
    return "\n".join(parts) + "\n"


def font_copies(vendor_fonts: Path, target: Path) -> dict[Path, Path]:
    """Target -> source of every font and licence file to copy next to `tokens.gen.ts`.

    Args:
        vendor_fonts: `tools/design-tokens/vendor/fonts` (checked against MANIFEST.json).
        target: `design/build/ts/fonts`.

    Returns:
        One entry per vendored file, same name, sorted.

    Raises:
        ValueError: a font family has no licence file `<family>.OFL.txt` next to its fonts.
    """
    sources = sorted(f for f in vendor_fonts.iterdir() if f.is_file())
    names = {f.name for f in sources}
    for f in sources:
        if f.suffix == ".woff2":
            family = re.sub(r"-latin(-ext)?-.*$", "", f.stem)
            if f"{family}.OFL.txt" not in names:
                raise ValueError(f"{f.name}: licence {family}.OFL.txt missing in {vendor_fonts}")
    return {target / f.name: f for f in sources}


def font_problems(copies: dict[Path, Path], target: Path) -> list[Path]:
    """Copies that are missing or differ from their source, and files in `target` that are no copy.

    Args:
        copies: result of `font_copies`.
        target: the directory of the copies.

    Returns:
        The affected paths, sorted.
    """
    problems = [dst for dst, src in copies.items() if not dst.is_file() or dst.read_bytes() != src.read_bytes()]
    if target.is_dir():
        problems += [f for f in target.iterdir() if f not in copies]
    return sorted(problems)
