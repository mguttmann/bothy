"""Design-token pipeline. One source (design/tokens, DTCG 2025.10), several outputs.

Usage (from the repository root):
  uv run tools/design-tokens/tokens.py build      # gates, then write all generated files
  uv run tools/design-tokens/tokens.py check      # gates, then fail if a generated file is stale
  uv run tools/design-tokens/tokens.py icons      # only the icon assets of packages/design_system
  uv run tools/design-tokens/tokens.py previews [--view NAME]  # render PNG previews with Playwright (needs npx)
  uv run tools/design-tokens/tokens.py vendor --phosphor DIR [--sans DIR --mono DIR]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from tokenkit import (  # noqa: E402
    accents,
    cvd,
    dtcg,
    emit_css,
    emit_dart,
    emit_docs,
    emit_preview,
    emit_ts,
    icon_assets,
    model,
    rules,
)

ROOT = HERE.parents[1]
RESOLVER = ROOT / "design" / "tokens" / "theme.resolver.json"
RULES = ROOT / "design" / "design-rules.json"
BUILD = ROOT / "design" / "build"
DOCS = ROOT / "docs" / "design"
VENDOR = HERE / "vendor"
# The package copy of the Dart output: a package may not import a file outside its folder
# (docs/spec/15-client-architektur.md 3.1), so `build` writes the same bytes twice and `check`
# compares both (docs/DECISIONS.md D-M4-04-1).
TS_FONTS = BUILD / "ts" / "fonts"
PACKAGE = ROOT / "packages" / "design_system"
PACKAGE_DART = PACKAGE / "lib" / "src" / "generated" / "design_tokens.g.dart"
# The icon assets (tokenkit/icon_assets.py) are compiled by vector_graphics_compiler of the Dart
# workspace lock; it runs in this package. The gate tests check a copy of the tree and point the
# variable at the real package, because a copy has no resolved workspace.
ICON_COMPILER_ENV = "DS_ICON_COMPILER_DIR"
ICON_HEADER = (
    "GENERATED by tools/design-tokens/tokens.py from design/tokens and tools/design-tokens/vendor/phosphor. "
    "Do not edit; change the source and rebuild."
)
HEADER = (
    "GENERIERT von tools/design-tokens/tokens.py aus design/tokens. Nicht bearbeiten; Quelle ändern und neu erzeugen."
)
PLAYWRIGHT = "playwright@1.56.1"

PREVIEWS = [
    # (view, theme, viewport, file stem)
    ("palette", "light", "1280,1180", "palette-light"),
    ("palette", "dark", "1280,1180", "palette-dark"),
    ("layout", "light", "1440,1000", "layout-light"),
    ("layout", "dark", "1440,1000", "layout-dark"),
    ("components", "light", "1280,1840", "components-light"),
    ("components", "dark", "1280,1840", "components-dark"),
    ("mobile", "light", "820,900", "mobile-light"),
    ("mobile", "dark", "820,900", "mobile-dark"),
    ("viz", "light", "1280,900", "viz-light"),
    ("viz", "dark", "1280,900", "viz-dark"),
]
VIEWS = tuple(dict.fromkeys(view for view, _, _, _ in PREVIEWS))


def _accents_json(variants: dict, default: str) -> dict:
    """Member `accents` of tokens.resolved.json: accent -> theme -> role -> hex, alias, moved_from, swapped."""
    out: dict = {}
    for (theme, accent), roles in variants.items():
        out.setdefault(accent, {})[theme] = {
            role: {"hex": v.hex, "alias": v.alias, "moved_from": v.moved_from, "swapped": v.swapped}
            for role, v in roles.items()
        }
    return {"default": default, "variants": out}


def _cvd_json(cvd_rows: list, rule_data: dict) -> dict:
    """Member `cvd` of tokens.resolved.json: model, minimum and one entry per checked pair."""
    return {
        "model": cvd.MODEL,
        "source": cvd.SOURCE,
        "min_delta_e_ok": rule_data["cvd_min_delta_e_ok"]["value"],
        "rows": [
            {
                "theme": r.theme,
                "deficiency": r.deficiency,
                "a": r.a,
                "b": r.b,
                "a_simulated": r.a_sim,
                "b_simulated": r.b_sim,
                "delta_e_ok": round(r.distance, 4),
                "passed": r.passed,
            }
            for r in cvd_rows
        ],
    }


def _resolved_json(
    m: model.Model, variants: dict | None = None, default: str = "", cvd_member: dict | None = None
) -> str:
    """The file tokens.resolved.json; `variants` and `default` add `accents`, `cvd_member` adds `cvd`."""

    def value(token: dtcg.Token):
        if token.type == "color":
            alpha = dtcg.color_alpha(token.value)
            return token.hex if alpha >= 1 else {"hex": token.hex, "alpha": alpha}
        return token.value

    data = {
        "$comment": HEADER,
        "defaults": m.defaults,
        "base": {p: {"type": t.type, "value": value(t)} for p, t in sorted(m.base.items())},
        "contexts": {
            name: {
                ctx: {p: {"type": t.type, "value": value(t)} for p, t in sorted(tokens.items())}
                for ctx, tokens in ctxs.items()
            }
            for name, ctxs in m.contexts.items()
        },
        "icons": emit_dart.icon_extension(m),
    }
    if variants:
        data["accents"] = _accents_json(variants, default)
    if cvd_member:
        data["cvd"] = cvd_member
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def _build_readme() -> str:
    return (
        "# design/build\n\n"
        f"{HEADER}\n\n"
        "| Datei | Inhalt | Verbraucher |\n"
        "|---|---|---|\n"
        "| `tokens.css` | CSS-Variablen (`--ds-*`), Theme, Dichte und Bewegung per Attribut oder Systemeinstellung "
        "| Doku-Site, Vorschau, Statusseite |\n"
        "| `dart/design_tokens.g.dart` | Konstanten und `ThemeExtension`-Klassen | `packages/design_system` |\n"
        "| `tokens.resolved.json` | alle Tokens aufgelöst, je Kontext "
        "| Server-Prüfung erlaubter Farb- und Icon-Schlüssel, Design-Werkzeuge |\n"
        "| `ts/tokens.gen.ts` | colour roles of both themes, font families, font sizes and radii as TypeScript "
        "constants; `ts/fonts/` holds the bundled fonts with their SIL Open Font License "
        "| Grafana panel plugin |\n"
        "| `preview.html` | eigenständige Vorschau (Schriften und Icons eingebettet) "
        "| Menschen, Playwright für `docs/design/previews/` |\n\n"
        "Erzeugen: `uv run tools/design-tokens/tokens.py build`. Prüfen: `make tokens`.\n"
    )


def generate() -> tuple[dict[Path, str], list[str]]:
    m = model.build(RESOLVER)
    rule_data = json.loads(RULES.read_text(encoding="utf-8"))
    themes = m.full["theme"]
    rows = rules.check_contrast(themes, rule_data["contrast_pairs"])
    default = rule_data.get("accent_variants", {}).get("default", "")
    try:
        variants = accents.derive(themes, rule_data)
        accent_problems: list[str] = []
    except accents.AccentContrastError as exc:
        variants, accent_problems = {}, [str(exc)]
    accent_rows = rules.check_accent_contrast(themes, rule_data["contrast_pairs"], variants, default)
    cvd_rows = rules.check_cvd(themes, rule_data)
    cvd_member = _cvd_json(cvd_rows, rule_data) if cvd_rows else None
    guard_problems: list[str] = []
    for ctx, tokens in themes.items():
        guard_problems += [f"[{ctx}] {p}" for p in rules.check_guards(tokens, rule_data["palette_guards"])]
    problems = [
        f"[{r.theme}] {r.fg} on {r.bg}: {r.ratio:.2f} < {r.required} ({r.fg_hex} on {r.bg_hex})"
        for r in rows
        if not r.passed
    ]
    problems += [
        f"[{r.theme}, accent {r.accent}] {r.fg} on {r.bg}: {r.ratio:.2f} < {r.required} ({r.fg_hex} on {r.bg_hex})"
        for r in accent_rows
        if not r.passed
    ]
    problems += [
        f"[{r.theme}, {r.deficiency}] {r.a} and {r.b}: deltaE_ok {r.distance:.3f} < {r.required:g} "
        f"({r.a_hex} and {r.b_hex}, simulated {r.a_sim} and {r.b_sim})"
        for r in cvd_rows
        if not r.passed
    ]
    problems += accent_problems + guard_problems
    dart = emit_dart.render(m, HEADER, variants, default)
    outputs = {
        BUILD / "README.md": _build_readme(),
        BUILD / "tokens.css": emit_css.render(m, HEADER, variants, default),
        BUILD / "dart" / "design_tokens.g.dart": dart,
        PACKAGE_DART: dart,
        BUILD / "ts" / "tokens.gen.ts": emit_ts.render(m),
        BUILD / "tokens.resolved.json": _resolved_json(m, variants, default, cvd_member),
        BUILD / "preview.html": emit_preview.render(m, VENDOR, HEADER),
        DOCS / "palette.md": emit_docs.palette_md(m, HEADER),
        DOCS / "contrast.md": emit_docs.contrast_md(
            rows, guard_problems, HEADER, accent_rows, variants, default, cvd_rows, rule_data.get("cvd_min_delta_e_ok")
        ),
        DOCS / "tokens.md": emit_docs.tokens_md(m, HEADER),
    }
    return outputs, problems


def icon_outputs() -> dict[Path, bytes]:
    """The icon assets of packages/design_system (absolute path to bytes), built in memory.

    Raises:
        icon_assets.IconError: a mapped glyph has no SVG, or the compiler failed.
    """
    icons = emit_dart.icon_extension(model.build(RESOLVER))
    compiler_dir = Path(os.environ.get(ICON_COMPILER_ENV) or PACKAGE)
    built = icon_assets.build(
        icons,
        VENDOR / "phosphor",
        ICON_HEADER,
        icon_assets.vector_compiler(compiler_dir),
        icon_assets.compiler_version(compiler_dir.parents[1] / "pubspec.lock"),
    )
    return {PACKAGE / rel: data for rel, data in built.items()}


def icon_extras(outputs: dict[Path, bytes]) -> list[Path]:
    """Files under packages/design_system/assets/icons/ that the icon build does not write."""
    asset_dir = PACKAGE / icon_assets.ASSET_DIR
    if not asset_dir.is_dir():
        return []
    return sorted(f for f in asset_dir.rglob("*") if f.is_file() and f not in outputs)


def _write_icons(outputs: dict[Path, bytes]) -> None:
    for extra in icon_extras(outputs):
        extra.unlink()
        print(f"removed {extra.relative_to(ROOT)}")
    for path, data in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f"wrote {len(outputs)} icon files under {PACKAGE.relative_to(ROOT)}")


def cmd_icons(_args) -> int:
    """Build only the icon assets (they need no design gate: their source is the mapping and vendor/)."""
    _write_icons(icon_outputs())
    return 0


def cmd_build(_args) -> int:
    # Icons first: a missing SVG is reported as a mapped glyph, before the preview reads vendor/.
    icons = icon_outputs()
    outputs, problems = generate()
    if problems:
        print("Design gates failed:", file=sys.stderr)
        for p in problems:
            print("  " + p, file=sys.stderr)
        return 1
    fonts = emit_ts.font_copies(VENDOR / "fonts", TS_FONTS)
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    TS_FONTS.mkdir(parents=True, exist_ok=True)
    # The directory holds only copies; a file the vendor set no longer has would ship stale.
    for extra in emit_ts.font_problems(fonts, TS_FONTS):
        if extra not in fonts:
            extra.unlink()
    for dst, src in fonts.items():
        shutil.copyfile(src, dst)
        print(f"copied {dst.relative_to(ROOT)}")
    _write_icons(icons)
    return 0


def cmd_check(_args) -> int:
    icons = icon_outputs()
    outputs, problems = generate()
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    fonts = emit_ts.font_copies(VENDOR / "fonts", TS_FONTS)
    stale += emit_ts.font_problems(fonts, TS_FONTS)
    stale += [p for p, data in icons.items() if not p.is_file() or p.read_bytes() != data]
    extras = icon_extras(icons)
    vendor = vendor_problems(VENDOR)
    for p in problems:
        print("gate: " + p, file=sys.stderr)
    for p in stale:
        print(f"stale: {p.relative_to(ROOT)} (run: uv run tools/design-tokens/tokens.py build)", file=sys.stderr)
    for p in extras:
        print(
            f"stale: {p.relative_to(ROOT)} (not generated; run: uv run tools/design-tokens/tokens.py build)",
            file=sys.stderr,
        )
    for p in vendor:
        print("vendor: " + p, file=sys.stderr)
    if problems or stale or extras or vendor:
        return 1
    print(
        f"ok: {len(outputs) + len(icons)} generated files and {len(fonts)} font copies up to date, "
        "all design gates pass, vendor/ matches MANIFEST.json"
    )
    return 0


def cmd_previews(args) -> int:
    html = BUILD / "preview.html"
    if not html.exists():
        print("design/build/preview.html missing; run build first", file=sys.stderr)
        return 1
    out_dir = DOCS / "previews"
    out_dir.mkdir(parents=True, exist_ok=True)
    npx = shutil.which("npx")
    if npx is None:
        print("npx not found; install Node.js", file=sys.stderr)
        return 1
    selected = [p for p in PREVIEWS if not args.view or p[0] in args.view]
    for view, theme, viewport, stem in selected:
        url = f"{html.as_uri()}?view={view}&theme={theme}"
        target = out_dir / f"{stem}.png"
        cmd = [
            npx,
            "-y",
            args.playwright,
            "screenshot",
            "--browser",
            "chromium",
            "--color-scheme",
            theme,
            "--viewport-size",
            viewport,
            "--wait-for-timeout",
            "400",
            url,
            str(target),
        ]
        print(" ".join(cmd[2:]))
        subprocess.run(cmd, check=True)
    return 0


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def as_stored(data: bytes) -> bytes:
    """Bytes as the repository stores them: text with LF line endings (.gitattributes), binary as is.

    A file without NUL byte counts as text, as in git's `text=auto`. Hashing the stored form
    keeps MANIFEST.json valid in every checkout, whatever line endings the upstream package used.
    """
    return data if b"\0" in data else data.replace(b"\r\n", b"\n")


def _copy_as_stored(src: Path, dst: Path) -> None:
    dst.write_bytes(as_stored(src.read_bytes()))


def vendor_problems(vendor: Path) -> list[str]:
    """Every file under fonts/ and phosphor/ is listed in MANIFEST.json with its sha256, and nothing else."""
    recorded: dict[str, str] = json.loads((vendor / "MANIFEST.json").read_text(encoding="utf-8"))["sha256"]
    present = {
        f.relative_to(vendor).as_posix(): f
        for sub in ("fonts", "phosphor")
        if (vendor / sub).is_dir()
        for f in (vendor / sub).iterdir()
        if f.is_file()
    }
    problems = [f"{name}: not listed in MANIFEST.json" for name in sorted(present.keys() - recorded.keys())]
    problems += [f"{name}: listed in MANIFEST.json but missing" for name in sorted(recorded.keys() - present.keys())]
    problems += [
        f"{name}: sha256 differs from MANIFEST.json (re-vendor with `tokens.py vendor`)"
        for name in sorted(present.keys() & recorded.keys())
        if _sha256(present[name]) != recorded[name]
    ]
    return problems


def cmd_vendor(args) -> int:
    """Copy the used Phosphor SVGs (and the font files when given) into vendor/ and write MANIFEST.json.

    Phosphor: every glyph of `ds.icons` in its mapped weight and in `fill`, every space icon in
    `regular` (`icon_assets.needed_svgs`), plus the LICENSE. Fonts: only when `--sans` and
    `--mono` are given; otherwise vendor/fonts/ stays as it is, so a new icon needs only the
    Phosphor package. Text files are stored with LF line endings (`as_stored`); MANIFEST.json
    records the sha256 of the stored bytes, and `check` verifies it.
    """
    if (args.sans is None) != (args.mono is None):
        print("--sans and --mono go together", file=sys.stderr)
        return 2
    m = model.build(RESOLVER)
    icons = emit_dart.icon_extension(m)
    phosphor = Path(args.phosphor)
    subs = ("fonts", "phosphor") if args.sans else ("phosphor",)
    previous = json.loads((VENDOR / "MANIFEST.json").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        staging = Path(tmp)
        for sub in subs:
            (staging / sub).mkdir()
        if args.sans:
            for src_dir, family in (
                (Path(args.sans), "atkinson-hyperlegible-next"),
                (Path(args.mono), "atkinson-hyperlegible-mono"),
            ):
                for name in (f"{family}-latin-wght-normal.woff2", f"{family}-latin-ext-wght-normal.woff2"):
                    _copy_as_stored(src_dir / "files" / name, staging / "fonts" / name)
                _copy_as_stored(src_dir / "LICENSE", staging / "fonts" / f"{family}.OFL.txt")
        for name, weight in icon_assets.needed_svgs(icons):
            file = icon_assets.svg_file(name, weight)
            _copy_as_stored(phosphor / "assets" / weight / file, staging / "phosphor" / file)
        _copy_as_stored(phosphor / "LICENSE", staging / "phosphor" / "LICENSE")
        for sub in subs:
            target = VENDOR / sub
            if target.exists():
                shutil.rmtree(target)
            shutil.copytree(staging / sub, target)
    files: dict[str, str] = {}
    for sub in ("fonts", "phosphor"):
        sub_dir = VENDOR / sub
        if sub_dir.is_dir():
            for f in sorted(sub_dir.iterdir()):
                files[f.relative_to(VENDOR).as_posix()] = _sha256(f)
    sources = dict(previous.get("sources", {}))
    if args.sans:
        sources["fonts/atkinson-hyperlegible-next-*"] = (
            f"npm @fontsource-variable/atkinson-hyperlegible-next@{args.sans_version} (OFL-1.1)"
        )
        sources["fonts/atkinson-hyperlegible-mono-*"] = (
            f"npm @fontsource-variable/atkinson-hyperlegible-mono@{args.mono_version} (OFL-1.1)"
        )
    sources["phosphor/*"] = f"npm @phosphor-icons/core@{icons['version']} (MIT)"
    manifest = {"$comment": previous.get("$comment", ""), "sources": sources, "sha256": files}
    (VENDOR / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"vendored {len(files)} files")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("build").set_defaults(func=cmd_build)
    sub.add_parser("check").set_defaults(func=cmd_check)
    sub.add_parser("icons").set_defaults(func=cmd_icons)
    p = sub.add_parser("previews")
    p.add_argument("--playwright", default=PLAYWRIGHT, help="npx package spec of the Playwright CLI")
    p.add_argument(
        "--view",
        action="append",
        choices=VIEWS,
        help="render only this view (repeatable); default: all, which re-renders every committed image",
    )
    p.set_defaults(func=cmd_previews)
    v = sub.add_parser("vendor")
    v.add_argument("--phosphor", required=True, help="unpacked @phosphor-icons/core package")
    v.add_argument("--sans", help="unpacked @fontsource-variable/atkinson-hyperlegible-next (with --mono)")
    v.add_argument("--mono", help="unpacked @fontsource-variable/atkinson-hyperlegible-mono (with --sans)")
    v.add_argument("--sans-version", default="5.3.0")
    v.add_argument("--mono-version", default="5.3.0")
    v.set_defaults(func=cmd_vendor)
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except (dtcg.TokenError, rules.RuleError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
