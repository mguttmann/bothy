// Gate G4 for TypeScript (docs/spec/06-api.md 15): the checked-in types come from the pinned
// generator; `make generate-check` proves that they equal a fresh generation and compile.

import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const root = new URL("../", import.meta.url);

function read(path: string): string {
  return readFileSync(new URL(path, root), "utf8");
}

describe("generated core", () => {
  it("G4: generated file carries the generator header", () => {
    const generated = read("src/generated/openapi.ts");
    expect(
      generated.startsWith(
        "/**\n * This file was auto-generated by openapi-typescript.\n",
      ),
    ).toBe(true);
    expect(generated).toContain("export interface paths {");
    expect(generated).toContain("export interface components {");
    expect(generated).toContain("export interface operations {");
    expect(generated).toContain("export interface webhooks {");
  });

  it("version matches VERSION file", () => {
    const manifest = JSON.parse(read("package.json")) as { version: string };
    expect(manifest.version).toBe(read("VERSION").trim());
  });
});
