// Command zonegen writes the list of IANA time zone names that the identity module accepts for
// users.time_zone (M1-31): every zone of the tzdata of the Go toolchain (GOROOT
// lib/time/zoneinfo.zip, the same data that time/tzdata embeds), without "Factory", whose name ICU
// and Intl refuse. A list instead of time.LoadLocation alone makes the rule independent of the
// host: a case-insensitive file system or a system zoneinfo directory with extra files would
// otherwise accept names production refuses (red team M1-31).
//
// It runs through go generate (directive in internal/identity/domain/people.go):
//
//	go generate ./internal/identity/domain/...
//
// Exit codes: 0 written, 1 I/O error, 2 usage error (also without -zip and GOROOT).
package main

import (
	"archive/zip"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"slices"
)

func main() { os.Exit(run(os.Args[1:], os.Stderr)) }

// run parses args (-zip, default the zip under $GOROOT, which go generate sets; -out, the file to write).
func run(args []string, stderr io.Writer) int {
	fs := flag.NewFlagSet("zonegen", flag.ContinueOnError)
	fs.SetOutput(stderr)
	zipPath := fs.String("zip", "", "zoneinfo.zip to read (default: GOROOT/lib/time/zoneinfo.zip)")
	out := fs.String("out", "", "Go file to write")
	if err := fs.Parse(args); err != nil || *out == "" {
		_, _ = fmt.Fprintln(stderr, "usage: zonegen [-zip zoneinfo.zip] -out file.go")
		return 2
	}
	if *zipPath == "" {
		// go generate sets GOROOT for the generator; the tool starts no command of its own.
		root := os.Getenv("GOROOT") //nolint:forbidigo // a go generate tool outside the server; go generate passes GOROOT
		if root == "" {
			_, _ = fmt.Fprintln(stderr, "zonegen: GOROOT is not set; run through go generate or pass -zip")
			return 2
		}
		*zipPath = filepath.Join(root, "lib", "time", "zoneinfo.zip")
	}
	names, err := Names(*zipPath)
	if err == nil {
		err = os.WriteFile(*out, Render(names), 0o600)
	}
	if err != nil {
		_, _ = fmt.Fprintln(stderr, "zonegen:", err)
		return 1
	}
	return 0
}

// Names returns the sorted zone names of the zip at path, without directories and "Factory".
func Names(path string) ([]string, error) {
	r, err := zip.OpenReader(path)
	if err != nil {
		return nil, err
	}
	defer func() { _ = r.Close() }()
	var names []string
	for _, f := range r.File {
		if f.FileInfo().IsDir() || f.Name == "Factory" {
			continue
		}
		names = append(names, f.Name)
	}
	if len(names) == 0 {
		return nil, errors.New("no zone in " + path)
	}
	slices.Sort(names)
	return names, nil
}

// Render returns the formatted Go file with the set zoneNames.
func Render(names []string) []byte {
	var b bytes.Buffer
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n\n// Code generated by tools/zonegen from the tzdata of the Go toolchain. DO NOT EDIT.\n\npackage domain\n\n")
	b.WriteString("// zoneNames are the IANA zone names users.time_zone accepts.\nvar zoneNames = map[string]bool{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: true,\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err) // the template above is valid Go
	}
	return src
}
