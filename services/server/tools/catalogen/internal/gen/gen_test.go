// TestCheckReserved: a catalogue entry whose identifier equals a name the package declares by
// hand (for example the resource kind "kind" gives ResourceKind) fails with entry and field.
func TestCheckReserved(t *testing.T) {
	c, err := gen.Parse(readFile(t, "valid.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	if err := gen.CheckReserved(c, []string{"Registry", "OpRegistration"}); err != nil {
		t.Fatalf("no collision expected: %v", err)
	}
	c.ResourceKinds = append(c.ResourceKinds, "kind")
	c.Events = append(c.Events, gen.Event{Type: "registration"})
	err = gen.CheckReserved(c, []string{"EventRegistration"})
	for _, w := range []string{"resources (kind)", "ResourceKind", "events (registration)", "EventRegistration"} {
		if err == nil || !strings.Contains(err.Error(), w) {
			t.Errorf("err = %v, want %q", err, w)
		}
	}
}

