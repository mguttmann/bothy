// TestParse_BooleanSpelling: YAML booleans count in any spelling YAML accepts.
func TestParse_BooleanSpelling(t *testing.T) {
	base := string(readFile(t, "valid.yaml"))
	c, err := gen.Parse([]byte(strings.Replace(base, "  owner: yes\n", "  owner: True\n", 1)))
	if err != nil {
		t.Fatal(err)
	}
	for _, a := range c.Actions {
		if a.ID == "agent.billing_mode.set_all" && !a.Owner {
			t.Fatal("owner True not read as true")
		}
	}
}
