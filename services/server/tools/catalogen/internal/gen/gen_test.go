// update rewrites the golden files: go test ./tools/catalogen/... -args -update. Review the diff.
var update = flag.Bool("update", false, "rewrite the golden files of testdata")

func readFile(t *testing.T, name string) []byte {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("testdata", name)) //nolint:gosec // G304: fixture names of this test
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// generate renders both files from testdata/valid.yaml.
func generate(t *testing.T) (ids, domain []byte) {
	t.Helper()
	c, err := gen.Parse(readFile(t, "valid.yaml"))
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	ids, err = gen.RenderIDs(c)
	if err != nil {
		t.Fatalf("RenderIDs: %v", err)
	}
	domain, err = gen.RenderDomain(c)
	if err != nil {
		t.Fatalf("RenderDomain: %v", err)
	}
	return ids, domain
}

func golden(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", name)
	if *update {
		if err := os.WriteFile(path, got, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path) //nolint:gosec // G304: golden file of this test
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s differs from the generated output; run with -args -update and review the diff\n--- got\n%s", name, got)
	}
}

// TestGenerate_Golden: the small catalogue with every normalisation case gives the checked-in
// files byte for byte.
func TestGenerate_Golden(t *testing.T) {
	ids, domain := generate(t)
	golden(t, "valid.ids.golden", ids)
	golden(t, "valid.domain.golden", domain)
}

func TestGenerate_Deterministic(t *testing.T) {
	ids1, domain1 := generate(t)
	ids2, domain2 := generate(t)
	if !bytes.Equal(ids1, ids2) || !bytes.Equal(domain1, domain2) {
		t.Fatal("two runs gave different bytes")
	}
}

// TestGenerate_Header: both files start with the SPDX line and the generated-code marker.
func TestGenerate_Header(t *testing.T) {
	ids, domain := generate(t)
	for name, b := range map[string][]byte{"ids": ids, "domain": domain} {
		if !bytes.HasPrefix(b, []byte("// SPDX-License-Identifier: Apache-2.0\n\n// Code generated by catalogen. DO NOT EDIT.\n")) {
			t.Errorf("%s: header %q", name, b[:min(len(b), 120)])
		}
	}
}

// TestParse_Normalisation checks the parsed values of the valid catalogue directly, so the golden
// files are not the only proof of each normalisation rule.
func TestParse_Normalisation(t *testing.T) {
	c, err := gen.Parse(readFile(t, "valid.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	byID := map[string]gen.Action{}
	for _, a := range c.Actions {
		byID[a.ID] = a
	}
	checks := []struct {
		name string
		ok   bool
	}{
		{"actions sorted", slices.IsSortedFunc(c.Actions, func(a, b gen.Action) int { return strings.Compare(a.ID, b.ID) })},
		{"owner yes", byID["agent.billing_mode.set_all"].Owner},
		{"step_up yes", byID["agent.billing_mode.set_all"].StepUp && !byID["agent.billing_mode.set_all"].StepUpConditional},
		{"rights true", byID["agent.billing_mode.set_all"].Rights},
		{"resource note dropped", slices.Equal(byID["agent.billing_mode.set_all"].Resources, []string{"instance", "space"})},
		{"resource list", slices.Equal(byID["passkey.add"].Resources, []string{"passkey", "user"})},
		{"as the target action", len(byID["access.preview"].Resources) == 0},
		{"owner as_target", !byID["access.preview"].Owner && byID["access.preview"].OwnerAsTarget},
		{"rights no", !byID["access.preview"].Rights},
		{"audit denials", byID["access.preview"].Audit == "denials"},
		{"audit conditional", byID["passkey.add"].Audit == "yes for others'"},
		{"audit always", byID["terminal.open"].Audit == "yes"},
		{"audit never", byID["message.read"].Audit == "no"},
		{"step_up conditional", byID["passkey.add"].StepUp && byID["passkey.add"].StepUpConditional},
		{"step_up conditional of a system action", byID["instance.bootstrap"].StepUpConditional},
		{"step_up fresh", byID["terminal.open"].StepUp && byID["terminal.open"].StepUpFresh},
		{"step_up fresh of a delivery check", byID["push.deliver"].StepUpFresh},
		{"class none", byID["instance.bootstrap"].RateLimitClass == ""},
		{"class none of a delivery check", byID["push.deliver"].RateLimitClass == ""},
		{"class kept", byID["message.read"].RateLimitClass == "rl.read"},
		{"system", byID["instance.bootstrap"].System && !byID["message.read"].System},
		{"right raw", byID["passkey.add"].Right == "self and `message.read`"},
		{"effect", byID["message.read"].Effect == "read" && byID["terminal.open"].Effect == "write"},
		{"delivery check", byID["push.deliver"].DeliveryCheck},
		{"app scope", byID["agent.billing_mode.set_all"].AppScope == "agents:write"},
		{"resource kinds", slices.Equal(c.ResourceKinds, []string{"instance", "message", "passkey", "principal", "space", "terminal_session", "user"})},
	}
	for _, ch := range checks {
		if !ch.ok {
			t.Errorf("%s: wrong value", ch.name)
		}
	}

	events := map[string]gen.Event{}
	for _, e := range c.Events {
		events[e.Type] = e
	}
	if e := events["message.created"]; !e.Durable || e.ReceiveAction != "`message.read`" || !slices.Equal(e.MentionedActions, []string{"message.read"}) || !e.ResourceVersion {
		t.Errorf("message.created: %+v", e)
	}
	if e := events["access.changed"]; !e.AudienceSelf || e.ReceiveAction != "self" || len(e.MentionedActions) != 0 || e.Receivers != "agent" {
		t.Errorf("access.changed: %+v", e)
	}
	if e := events["notice.created"]; !slices.Equal(e.Resources, []string{"message", "user"}) {
		t.Errorf("notice.created: the backticked kind of the note after the semicolon counts: %+v", e)
	}
	if e := events["typing.started"]; e.Durable || !slices.Equal(e.MentionedActions, []string{"message.read", "push.deliver"}) ||
		!slices.Equal(e.Resources, []string{"instance", "space"}) || e.Resource != "instance, space" {
		t.Errorf("typing.started: %+v", e)
	}

	ops := map[string]gen.Op{}
	for _, o := range c.Ops {
		ops[o.Op] = o
	}
	if len(ops) != 5 || ops["typing.start"].ActionsText != "`message.read`" || ops["typing.stop"].Direction != "client_to_server" {
		t.Errorf("op names split: %+v", c.Ops)
	}
	if o := ops["heartbeat"]; !slices.Equal(o.MentionedActions, []string{"message.read", "passkey.add"}) {
		t.Errorf("heartbeat: %+v", o)
	}
	if o := ops["dispatch"]; !o.PerEventReceiveAction || !slices.Equal(o.MentionedActions, []string{"message.read"}) {
		t.Errorf("dispatch: %+v", o)
	}
	if len(c.ChannelOps) != 2 || c.ChannelOps[0].Op != "hello" || c.ChannelOps[1].Op != "session.open" ||
		c.ChannelOps[1].Channel != "host_control" || c.ChannelOps[1].Action != "terminal.open" || c.ChannelOps[1].Direction != "server_to_host" {
		t.Errorf("channel ops: %+v", c.ChannelOps)
	}
}

// TestParse_Failures: every broken fixture fails with a message that names the entry and the field.
func TestParse_Failures(t *testing.T) {
	cases := []struct {
		file string
		want []string
	}{
		{"duplicate-action.yaml", []string{"actions[1] (message.read)", "id", "duplicate"}},
		{"identifier-collision.yaml", []string{"a_b.c", "id", "ActionABC", "a.b_c"}},
		{"unknown-key.yaml", []string{"actions[0] (message.read)", "colour", "unknown key"}},
		{"owner-value.yaml", []string{"actions[0] (message.read)", "owner", "maybe"}},
		{"unknown-class.yaml", []string{"actions[0] (message.read)", "rl_class", "rl.fast"}},
		{"resource-text.yaml", []string{"actions[0] (message.read)", "resource", "thread or channel"}},
		{"resource-note-then-text.yaml", []string{"actions[0] (message.read)", "resource", "terminal_session (a) or channel (b)"}},
		{"id-pattern.yaml", []string{"actions[0] (Message.Read)", "id", "Message.Read"}},
	}
	for _, tc := range cases {
		t.Run(tc.file, func(t *testing.T) {
			_, err := gen.Parse(readFile(t, filepath.Join("invalid", tc.file)))
			if err == nil {
				t.Fatal("Parse accepted the fixture")
			}
			for _, w := range tc.want {
				if !strings.Contains(err.Error(), w) {
					t.Errorf("error %q does not contain %q", err, w)
				}
			}
		})
	}
}

