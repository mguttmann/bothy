package gosplit

import (
	"go/parser"
	"go/token"
	"strings"
	"testing"
)

// input has a header, two imports used by different declarations and four declarations.
const input = `// Code generated by a test. DO NOT EDIT.
package p

import (
	"strings"
	"time"
)

// A is a type.
type A struct{ At time.Time }

// B uses strings.
func B() string { return strings.ToUpper("b") }

// C is a constant.
const C = 1

// D uses time.
func D() time.Duration { return time.Second }
`

// TestChunks_SplitsBelowLimit: every part is valid Go of the same package with the header, stays
// below the limit, imports only what it uses, and the parts keep every declaration in order.
func TestChunks_SplitsBelowLimit(t *testing.T) {
	limit := 200 // header and imports plus about two declarations
	parts, err := Chunks([]byte(input), limit)
	if err != nil {
		t.Fatal(err)
	}
	if len(parts) < 2 {
		t.Fatalf("got %d parts, want at least 2", len(parts))
	}
	var all strings.Builder
	for i, p := range parts {
		if len(p) > limit {
			t.Errorf("part %d has %d bytes, above %d", i, len(p), limit)
		}
		f, err := parser.ParseFile(token.NewFileSet(), "p.go", p, parser.ParseComments)
		if err != nil {
			t.Fatalf("part %d is not valid Go: %v\n%s", i, err, p)
		}
		if f.Name.Name != "p" || !strings.HasPrefix(string(p), "// Code generated by a test. DO NOT EDIT.") {
			t.Errorf("part %d lost the package or the header:\n%s", i, p)
		}
		for _, imp := range f.Imports {
			name := strings.Trim(imp.Path.Value, `"`)
			if !strings.Contains(string(p), name+".") {
				t.Errorf("part %d imports %s without using it", i, name)
			}
		}
		all.Write(p)
	}
	order := []string{"type A", "func B", "const C", "func D"}
	last := -1
	for _, d := range order {
		i := strings.Index(all.String(), d)
		if i < last {
			t.Errorf("%s is missing or out of order", d)
		}
		last = i
	}
}

// TestChunks_OnePartWhenSmall: a file below the limit stays one part.
func TestChunks_OnePartWhenSmall(t *testing.T) {
	parts, err := Chunks([]byte(input), 1<<20)
	if err != nil || len(parts) != 1 {
		t.Fatalf("Chunks = %d parts, %v; want 1, nil", len(parts), err)
	}
}

// TestChunks_Errors: a declaration above the limit and invalid Go are errors.
func TestChunks_Errors(t *testing.T) {
	if _, err := Chunks([]byte(input), 10); err == nil {
		t.Error("Chunks = nil error for a declaration above the limit")
	}
	if _, err := Chunks([]byte("package p\nfunc ("), 1<<20); err == nil {
		t.Error("Chunks = nil error for invalid Go")
	}
}
