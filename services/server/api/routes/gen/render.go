package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
	"text/template"
)

// header is the first line of every file the generator writes; it matches the Go convention
// for generated code, which linters and the coverage gate use to recognise it.
const header = "// Code generated by api/routes/gen; DO NOT EDIT."

// renderData is the input of the route file templates.
type renderData struct {
	Header  string
	Q       string // qualifier of the core types: "" in api/routes, "routes." elsewhere
	CorePkg string // import path of api/routes when Q is set
	RestPkg string // import path of the generated rest package
	Ops     []opMeta
	Actions []catalogAction
	// SpecVersion, Problems and GatewayVersions fill meta.gen.go (M1-46).
	SpecVersion     string
	Problems        []problemType
	GatewayVersions []int
	// GatewayOps fill GatewayOps in meta.gen.go (M1-64).
	GatewayOps []gatewayOp
}

var funcs = template.FuncMap{
	"quote": strconv.Quote,
	"ifmatch": func(m ifMatch) string {
		return map[ifMatch]string{ifMatchNone: "IfMatchNone", ifMatchOptional: "IfMatchOptional", ifMatchRequired: "IfMatchRequired"}[m]
	},
	"body": func(k bodyKind) string {
		return map[bodyKind]string{bodyNone: "BodyNone", bodyJSON: "BodyJSON", bodyMultipart: "BodyMultipart", bodyOctetStream: "BodyOctetStream", bodyReport: "BodyReport"}[k]
	},
	"ints": func(xs []int) string {
		if len(xs) == 0 {
			return "nil"
		}
		parts := make([]string, len(xs))
		for i, x := range xs {
			parts[i] = strconv.Itoa(x)
		}
		return "[]int{" + strings.Join(parts, ", ") + "}"
	},
}

var routesTemplate = template.Must(template.New("routes").Funcs(funcs).Parse(`{{.Header}}

package routes
{{if .Q}}
import routes {{quote .CorePkg}}
{{end}}
// operations are the operations of the enable list's section enabled, sorted by operation ID,
// with the metadata the spec declares for them.
var operations = []{{.Q}}Operation{
{{- range .Ops}}
	{
		ID:             {{quote .ID}},
		Method:         {{quote .Method}},
		Path:           {{quote .Path}},
		Pattern:        {{quote .Pattern}},
		Action:         {{quote .Action}},
		RateLimitClass: {{quote .RateLimitClass}},
		Public:         {{.Public}},
		IdempotencyKey: {{.IdempotencyKey}},
		IfMatch:        {{$.Q}}{{ifmatch .IfMatch}},
		RequestBody:    {{$.Q}}{{body .RequestBody}},
		BodyRequired:   {{.BodyRequired}},
		ETagStatuses:   {{ints .ETagStatuses}},
		Download:       {{.Download}},
{{- if .OwnCredential}}
		OwnCredential:  true,
{{- end}}
	},
{{- end}}
{{- if .Ops}}
{{end}}}
`))

var catalogTemplate = template.Must(template.New("catalog").Funcs(funcs).Parse(`{{.Header}}

package routes
{{if .Q}}
import routes {{quote .CorePkg}}
{{end}}
// catalogEntries are the actions of the action catalogue with their right and rate-limit class,
// sorted by ID.
var catalogEntries = []{{.Q}}CatalogEntry{
{{- range .Actions}}
	{ID: {{quote .ID}}, Right: {{quote .Right}}, RateLimitClass: {{quote .Class}}},
{{- end}}
{{- if .Actions}}
{{end}}}
`))

var buildTemplate = template.Must(template.New("build").Funcs(funcs).Parse(`{{.Header}}

package routes
{{if .Ops}}
import (
{{- if .Q}}
	routes {{quote .CorePkg}}
{{- end}}
	rest {{quote .RestPkg}}
)

// Server is the interface the handlers of all enabled operations implement together: the
// strict server interface generated from the enabled operations.
type Server = rest.StrictServerInterface

// register runs the generated strict and std-http server for impl on mux, below the base URL,
// with the error handlers of opts (nil keeps the oapi-codegen default).
func register(impl Server, opts {{.Q}}Options, mux *{{.Q}}Recorder) {
	strict := rest.NewStrictHandlerWithOptions(impl, nil, rest.StrictHTTPServerOptions{
		RequestErrorHandlerFunc:  opts.RequestErrorHandlerFunc,
		ResponseErrorHandlerFunc: opts.ResponseErrorHandlerFunc,
	})
	rest.HandlerWithOptions(strict, rest.StdHTTPServerOptions{
		BaseURL:          {{.Q}}BaseURL,
		BaseRouter:       mux,
		ErrorHandlerFunc: opts.ErrorHandlerFunc,
	})
}
{{- else}}
{{- if .Q}}
import routes {{quote .CorePkg}}
{{end}}
// Server is any while no operation is enabled: there is no generated interface to implement,
// whatever oapi-codegen emits for zero operations.
type Server = any

// register registers nothing while no operation is enabled.
func register(Server, {{.Q}}Options, *{{.Q}}Recorder) {}
{{- end}}
`))

var metaTemplate = template.Must(template.New("meta").Funcs(funcs).Parse(`{{.Header}}

package routes
{{if .Q}}
import routes {{quote .CorePkg}}
{{end}}
// SpecVersion is info.version of the OpenAPI document this server implements; discovery and
// getInstance report it (06 section 13 item 1).
const SpecVersion = {{quote .SpecVersion}}

// GatewayProtocolVersions returns info.x-protocol-versions of the AsyncAPI document, the gateway
// protocol versions this server speaks, sorted (04 section 6.1); a fresh slice per call, nil
// when the generator read no AsyncAPI document.
func GatewayProtocolVersions() []int {
	return {{ints .GatewayVersions}}
}

// GatewayOps returns the enabled ops of the section gateway_ops of the enable list, each with the
// action of its x-authz-action and the schema of its body in the AsyncAPI document, sorted by op
// (04 section 6.2, 05 "WebSocket ops and action"); a fresh slice per call, nil when the generator
// read no AsyncAPI document. The gateway dispatcher registers exactly these ops (M1-64).
func GatewayOps() []{{.Q}}GatewayOp {
{{- if .GatewayOps}}
	return []{{.Q}}GatewayOp{
{{- range .GatewayOps}}
		{Op: {{quote .Op}}, Action: {{quote .Action}}, Schema: {{quote .Schema}}},
{{- end}}
	}
{{- else}}
	return nil
{{- end}}
}

// ProblemTypes returns x-problem-codes of the schema Problem, the one catalogue of problem codes
// (06 section 5, R-API-23), sorted by code; a fresh slice per call.
func ProblemTypes() []{{.Q}}ProblemType {
{{- if .Problems}}
	return []{{.Q}}ProblemType{
{{- range .Problems}}
		{Code: {{quote .Code}}, Status: {{.Status}}, Title: {{quote .Title}}, Description: {{quote .Description}}, ClientAction: {{quote .ClientAction}}},
{{- end}}
	}
{{- else}}
	return nil
{{- end}}
}
`))

// renderRoutes renders routes.gen.go, catalog.gen.go, build.gen.go and meta.gen.go for the enabled
// operations of in. corePkg is the import path of api/routes, or "" when the files go into
// api/routes itself; restPkg is the import path of the generated rest package.
func renderRoutes(in *inputs, corePkg, restPkg string) (map[string][]byte, error) {
	data := renderData{
		Header: header, CorePkg: corePkg, RestPkg: restPkg, Actions: in.actions,
		SpecVersion: in.specVersion, Problems: in.problems, GatewayVersions: in.gatewayVersions,
		GatewayOps: in.gatewayOps,
	}
	if corePkg != "" {
		data.Q = "routes."
	}
	for _, op := range in.ops {
		if in.enabled[op.ID] {
			data.Ops = append(data.Ops, op)
		}
	}
	out := map[string][]byte{}
	for name, tmpl := range map[string]*template.Template{
		"routes.gen.go":  routesTemplate,
		"catalog.gen.go": catalogTemplate,
		"build.gen.go":   buildTemplate,
		"meta.gen.go":    metaTemplate,
	} {
		var buf bytes.Buffer
		if err := tmpl.Execute(&buf, data); err != nil {
			return nil, fmt.Errorf("render %s: %w", name, err)
		}
		src, err := format.Source(buf.Bytes())
		if err != nil {
			return nil, fmt.Errorf("render %s: %w\n%s", name, err, buf.String())
		}
		out[name] = src
	}
	return out, nil
}
