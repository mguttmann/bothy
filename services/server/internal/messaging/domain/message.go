// HashInput are the fields of the canonical request (04 section 5.1 point 3).
type HashInput struct {
	// Context is "thread:<id>" for createMessage, "new-thread:..." for createThread (brief D8).
	Context string
	// Kind is the message kind; an absent kind is "text".
	Kind string
	// Content is content_md.
	Content string
	// ReplyTo is the reply target id, "" for none.
	ReplyTo string
	// AttachmentIDs are the attachment ids in request order.
	AttachmentIDs []string
	// RunID is run_id, "" when absent (M2-15).
	RunID string
	// Card is the canonical form of the components (messaging.CheckedCard.Canonical); nil
	// without components (M2-15).
	Card []byte
}

// hashVersion starts the encoding; a new encoding gets a new prefix, never an edit.
// hashVersionCard is the encoding of a request with components or run_id (M2-15 design note
// 6 c): the fields of v1 in v1 order, then run_id and the canonical card.
const (
	hashVersion     = "bothy-msg-v1"
	hashVersionCard = "bothy-msg-v2"
)

// RequestHash returns client_payload_sha256 (brief D3): SHA-256 over the version prefix, then each
// field as uvarint(length) and its bytes, so JSON key order and white space cannot change it and
// no field boundary can move. A request with neither RunID nor Card keeps bothy-msg-v1 byte for
// byte, so a message stored before M2-15 still replays; one with either uses bothy-msg-v2 (ruling
// D-M2-15-7).
func RequestHash(in HashInput) []byte {
	h := sha256.New()
	fields := [][]byte{[]byte(in.Context), []byte(in.Kind), []byte(in.Content), []byte(in.ReplyTo),
		[]byte(strings.Join(in.AttachmentIDs, ","))}
	if in.RunID == "" && in.Card == nil {
		h.Write([]byte(hashVersion))
	} else {
		h.Write([]byte(hashVersionCard))
		fields = append(fields, []byte(in.RunID), in.Card)
	}
	for _, f := range fields {
		var n [binary.MaxVarintLen64]byte
		h.Write(n[:binary.PutUvarint(n[:], uint64(len(f)))])
		h.Write(f)
	}
	return h.Sum(nil)
}

// SystemLine returns the system line code leaves at seq in the thread (brief D6): kind system,
// origin system, empty content, silent, author the principal whose message caused it, a new
// server client_msg_id and the hash of its own canonical form.
func SystemLine(code string, thread, channel, author ids.ID, seq int64) Message {
	return Message{
		ID: ids.New(), ThreadID: thread, ChannelID: channel, ThreadSeq: seq, AuthorID: author, ClientMsgID: ids.New(),
		PayloadSHA256: RequestHash(HashInput{Context: "system:" + code, Kind: string(KindSystem)}),
		Origin:        OriginSystem, Kind: KindSystem, SystemCode: code, ContentFormat: ContentFormat, Silent: true, Version: 1,
	}
}

// RunAnchor returns the live box anchor of run by agent at seq in the thread (09 section 5.4,
// M2-05): kind run, origin agent, empty content, silent (the anchor notifies nobody), a new server
// client_msg_id and the hash of its own canonical form, whose context names the run.
func RunAnchor(run, thread, channel, agent ids.ID, seq int64) Message {
	return Message{
		ID: ids.New(), ThreadID: thread, ChannelID: channel, ThreadSeq: seq, AuthorID: agent, ClientMsgID: ids.New(),
		PayloadSHA256: RequestHash(HashInput{Context: "run-anchor:" + run.String(), Kind: string(KindRun)}),
		Origin:        OriginAgent, Kind: KindRun, ContentFormat: ContentFormat, RunID: run, Silent: true, Version: 1,
	}
}

// triggerStates are the values of schema TriggerState (09 section 6); true marks the states that
// carry a reason (03 messages_trigger_reason_check).
var triggerStates = map[string]bool{
	"received": false, "queued": false, "working": false, "done": false, "failed": true, "cancelled": true,
	"followup_delivered": false,
}

// CheckTriggerState accepts a value of schema TriggerState with a non-empty reason exactly for
// failed and cancelled. The caller (runs) builds both, so a refusal is a programming error.
// Errors: internal.
func CheckTriggerState(state, reason string) error {
	withReason, ok := triggerStates[state]
	if !ok {
		return errs.New(errs.CodeInternalError, "messaging: an unknown trigger state")
	}
	if withReason != (reason != "") {
		return errs.New(errs.CodeInternalError, "messaging: a trigger state reason that does not fit the state")
	}
	return nil
}

// TruncateForEvent returns content cut to the longest prefix at a character boundary for which
// fits reports true, and whether it cut (04 payload rule 2, brief D7). fits must be monotonic:
// a shorter prefix never fits worse. When not even the empty prefix fits it returns "" and true.
func TruncateForEvent(content string, fits func(prefix string) bool) (string, bool) {
	if fits(content) {
		return content, false
	}
	// P(n) = fits(content[:runeStart(n)]) is monotonic in n, true at lo and false at hi.
	lo, hi := 0, len(content)
	for hi-lo > 1 {
		mid := lo + (hi-lo)/2
		if fits(content[:runeStart(content, mid)]) {
			lo = mid
		} else {
			hi = mid
		}
	}
	return content[:runeStart(content, lo)], true
}

// runeStart returns the largest character boundary at or below i.
func runeStart(s string, i int) int {
	if i >= len(s) {
		return len(s)
	}
	for i > 0 && !utf8.RuneStart(s[i]) {
		i--
	}
	return i
}
