// Field error codes of the message rules (brief M1-56 D2, D5, D8).
const (
	// FieldNotUUIDv7 marks a client_msg_id that is not a UUIDv7.
	FieldNotUUIDv7 = "not_uuid_v7"
	// FieldNotEnabled marks a member whose function this server version does not build yet (06
	// section 5 item 3).
	FieldNotEnabled = "not_enabled"
	// FieldEmpty marks a text message without a non-space character.
	FieldEmpty = "empty"
	// FieldInvalid marks content PostgreSQL cannot store (U+0000).
	FieldInvalid = "invalid"
	// FieldNotInThread marks a reply to a message outside the thread, or to an unknown one.
	FieldNotInThread = "not_in_thread"
	// FieldMentionMismatch marks mention_ids that differ from the resolved set.
	FieldMentionMismatch = "mention_mismatch"
	// FieldTooManyMentions marks more than message.max_mentions distinct handles.
	FieldTooManyMentions = "too_many_mentions"
	// FieldRequiredForForumPost marks a forum post without first_message.
	FieldRequiredForForumPost = "required_for_forum_post"
)

// Origin is messages.origin (09 section 3.2): set by the server, never by a client.
type Origin string

// The origins of M1; import follows with M8.
const (
	OriginHuman  Origin = "human"
	OriginAgent  Origin = "agent"
	OriginApp    Origin = "app"
	OriginSystem Origin = "system"
)

// Kind is messages.kind (03 messages).
type Kind string

// The kinds; M1 writes only text and system (voice M3-09, card M2-15, run M2-05).
const (
	KindText   Kind = "text"
	KindVoice  Kind = "voice"
	KindCard   Kind = "card"
	KindRun    Kind = "run"
	KindSystem Kind = "system"
)

// SystemThreadReopened is the system_code of the line a reopening message leaves (03 messages,
// R-DM-34). The column CHECK holds every code of 03; M2-12 adds agent_session.resume_failed.
const SystemThreadReopened = "thread.reopened"

// ContentFormat is content_format 1: CommonMark 0.31.2 without raw HTML, with mention tokens.
const ContentFormat = 1

// Message is one row of messages as M1 writes and reads it. Zero values are NULL.
type Message struct {
	ID, ThreadID, ChannelID ids.ID
	// ThreadSeq is the gapless position in the thread.
	ThreadSeq int64
	// AuthorID is the author; for a system line the principal whose message caused it.
	AuthorID ids.ID
	// ClientMsgID is the idempotency key of the author; generated by the server for a system line.
	ClientMsgID ids.ID
	// PayloadSHA256 is the canonical request hash (RequestHash).
	PayloadSHA256 []byte
	Origin        Origin
	Kind          Kind
	// SystemCode is set exactly for KindSystem.
	SystemCode string
	// ContentMD is the content byte for byte; empty for a system line.
	ContentMD string
	// ContentFormat is the dialect version (smallint).
	ContentFormat int16
	// ReplyToID is the quoted message of the same thread; zero for none.
	ReplyToID ids.ID
	// Silent suppresses notifications.
	Silent bool
	// Version is the row version, 1 at creation.
	Version int64
	// EditedAt, DeletedAt and DeletedBy are zero until M1-58 edits or deletes.
	EditedAt, DeletedAt time.Time
	DeletedBy           ids.ID
	// CreatedAt is the creation time.
	CreatedAt time.Time
}

// OriginFor returns the origin of a message by a principal of kind (user, agent or app; 09
// section 3.2). Errors: internal for a kind that never writes messages (host, anonymous).
func OriginFor(kind string) (Origin, error) {
	switch kind {
	case "user":
		return OriginHuman, nil
	case "agent":
		return OriginAgent, nil
	case "app":
		return OriginApp, nil
	}
	return "", errs.New(errs.CodeInternalError, "messaging: a principal of this kind writes no messages")
}

// fieldError is a validation_failed with one field error.
func fieldError(pointer, code, detail string) error {
	return errs.New(errs.CodeValidationFailed, detail).WithFields(errs.FieldError{Pointer: pointer, Code: code, Detail: detail})
}

// CheckClientMsgID refuses an id that is not a UUIDv7 with the RFC variant; the time inside is
// not checked, so an outbox may send old entries (04 section 5.1 point 5).
func CheckClientMsgID(id [16]byte) error {
	if id[6]>>4 != 7 || id[8]>>6 != 0b10 {
		return fieldError("/client_msg_id", FieldNotUUIDv7, "client_msg_id is not a UUIDv7")
	}
	return nil
}

// CheckContent checks the content of a text message (brief D2): a non-space character, no
// U+0000 (PostgreSQL text cannot hold it), at most maxBytes UTF-8 bytes. The content itself is
// stored unchanged (SEC-IN-4). Errors: validation_failed on /content_md, payload_too_large naming
// message.max_content_bytes.
func CheckContent(content string, maxBytes int) error {
	if len(content) > maxBytes {
		return errs.New(errs.CodePayloadTooLarge, "content_md is larger than message.max_content_bytes")
	}
	if strings.IndexByte(content, 0) >= 0 {
		return fieldError("/content_md", FieldInvalid, "content_md contains U+0000")
	}
	if strings.IndexFunc(content, func(r rune) bool { return !unicode.IsSpace(r) }) < 0 {
		return fieldError("/content_md", FieldEmpty, "content_md has no visible character")
	}
	return nil
}

// CheckMentionCount refuses more than maxMentions distinct handles (03 messages, content format
// item 5).
func CheckMentionCount(handles []string, maxMentions int) error {
	if len(handles) > maxMentions {
		return fieldError("/content_md", FieldTooManyMentions, "content_md names more handles than message.max_mentions")
	}
	return nil
}

// NotEnabled is the 400 of a member whose function M1 does not build (brief D2).
func NotEnabled(pointer string) error {
	return fieldError(pointer, FieldNotEnabled, "this member is not enabled in this server version")
}

// NotInThread is the 400 of a reply target outside the thread; an unknown id gets the same.
func NotInThread() error {
	return fieldError("/reply_to_message_id", FieldNotInThread, "the message is not in this thread")
}

// MentionMismatch is the 400 of mention_ids that differ from the resolved set.
func MentionMismatch() error {
	return fieldError("/mention_ids", FieldMentionMismatch, "mention_ids differ from the mentions of content_md")
}

// RequiredForForumPost is the 400 of a forum post without first_message.
func RequiredForForumPost() error {
	return fieldError("/first_message", FieldRequiredForForumPost, "a forum post needs its first message")
}

// HashInput are the fields of the canonical request (04 section 5.1 point 3).
type HashInput struct {
	// Context is "thread:<id>" for createMessage, "new-thread:..." for createThread (brief D8).
	Context string
	// Kind is the message kind; an absent kind is "text".
	Kind string
	// Content is content_md.
	Content string
	// ReplyTo is the reply target id, "" for none.
	ReplyTo string
	// AttachmentIDs are the attachment ids in request order.
	AttachmentIDs []string
}

// hashVersion starts the encoding; a new encoding gets a new prefix, never an edit.
const hashVersion = "bothy-msg-v1"

// RequestHash returns client_payload_sha256 (brief D3): SHA-256 over hashVersion, then each field
// as uvarint(length) and its bytes, so JSON key order and white space cannot change it and no
// field boundary can move.
func RequestHash(in HashInput) []byte {
	h := sha256.New()
	h.Write([]byte(hashVersion))
	for _, f := range []string{in.Context, in.Kind, in.Content, in.ReplyTo, strings.Join(in.AttachmentIDs, ",")} {
		var n [binary.MaxVarintLen64]byte
		h.Write(n[:binary.PutUvarint(n[:], uint64(len(f)))])
		h.Write([]byte(f))
	}
	return h.Sum(nil)
}

// SystemLine returns the system line code leaves at seq in the thread (brief D6): kind system,
// origin system, empty content, silent, author the principal whose message caused it, a new
// server client_msg_id and the hash of its own canonical form.
func SystemLine(code string, thread, channel, author ids.ID, seq int64) Message {
	return Message{
		ID: ids.New(), ThreadID: thread, ChannelID: channel, ThreadSeq: seq, AuthorID: author, ClientMsgID: ids.New(),
		PayloadSHA256: RequestHash(HashInput{Context: "system:" + code, Kind: string(KindSystem)}),
		Origin:        OriginSystem, Kind: KindSystem, SystemCode: code, ContentFormat: ContentFormat, Silent: true, Version: 1,
	}
}

// TruncateForEvent returns content cut to the longest prefix at a character boundary for which
// fits reports true, and whether it cut (04 payload rule 2, brief D7). fits must be monotonic:
// a shorter prefix never fits worse. When not even the empty prefix fits it returns "" and true.
func TruncateForEvent(content string, fits func(prefix string) bool) (string, bool) {
	if fits(content) {
		return content, false
	}
	// P(n) = fits(content[:runeStart(n)]) is monotonic in n, true at lo and false at hi.
	lo, hi := 0, len(content)
	for hi-lo > 1 {
		mid := lo + (hi-lo)/2
		if fits(content[:runeStart(content, mid)]) {
			lo = mid
		} else {
			hi = mid
		}
	}
	return content[:runeStart(content, lo)], true
}

// runeStart returns the largest character boundary at or below i.
func runeStart(s string, i int) int {
	if i >= len(s) {
		return len(s)
	}
	for i > 0 && !utf8.RuneStart(s[i]) {
		i--
	}
	return i
}
