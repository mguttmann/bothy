// ActiveAppInstallation is the active installation of an app as identity needs it: its id and
// app_installations.granted_scopes (M2-24 design note 10).
type ActiveAppInstallation struct {
	ID            ids.ID
	GrantedScopes []string
}

// AppInstallations is the consumer port through which identity reads the installation of an app
// principal; the module apps implements it (apps/adapters/identitysource) and internal/wire binds
// it, so identity never imports apps (02 section 4.4, M2-24 design note 12). The installation is
// part of the credential of an app: an app whose installation is not active is unauthenticated
// with reason app_not_installed (07 section 4.1), gets no API token and has an empty rights
// snapshot. Both methods join the ambient unit of work of ctx when there is one.
type AppInstallations interface {
	// ActiveInstallation returns the installation of appID with state active; found is false
	// when there is none (no installation, suspended or uninstalled). It reads on every call, no
	// cache (AZ-P9).
	ActiveInstallation(ctx context.Context, appID ids.ID) (inst ActiveAppInstallation, found bool, err error)
	// LockActiveInstallation is ActiveInstallation with a FOR SHARE lock on the row in the
	// ambient unit of work, so an uninstall that holds the row FOR UPDATE and a token creation
	// serialize (M2-24 design note 10 a). Outside a unit of work it fails with internal.
	LockActiveInstallation(ctx context.Context, appID ids.ID) (inst ActiveAppInstallation, found bool, err error)
}

// NoAppInstallations is the AppInstallations of a process or test without the module apps: no app
// is ever installed, so app tokens are refused and apps have no rights (fail closed).
type NoAppInstallations struct{}

// Compile-time check: NoAppInstallations is the port.
var _ AppInstallations = NoAppInstallations{}

// ActiveInstallation implements AppInstallations: never found.
func (NoAppInstallations) ActiveInstallation(context.Context, ids.ID) (ActiveAppInstallation, bool, error) {
	return ActiveAppInstallation{}, false, nil
}

// LockActiveInstallation implements AppInstallations: never found.
func (NoAppInstallations) LockActiveInstallation(context.Context, ids.ID) (ActiveAppInstallation, bool, error) {
	return ActiveAppInstallation{}, false, nil
}

// NewPrincipalCmd is the input of PrincipalWrites.CreatePrincipal: a principal that is not a
// person (kind agent or app). The id is generated by the caller (UUIDv7, before its unit of
// work), so a rights change can name it.
type NewPrincipalCmd struct {
	ID ids.ID
	// Kind is actor.KindAgent or actor.KindApp.
	Kind actor.Kind
	// Handle follows ^[a-z0-9][a-z0-9._-]*$ with at most principal.handle_max_chars characters
	// and is unique without regard to case.
	Handle string
	// DisplayName is not blank, free of control and bidi characters and at most
	// principal.display_name_max_chars characters.
	DisplayName string
}

// PrincipalWrites is the writing port of identity for the principals of agents and apps (M2-24;
// M1-51 uses it for agents). It authorizes nothing: the calling use case did. Every method runs
// only inside the caller's unit of work; a status change is a rights change the caller declares
// (txn.DeclareRightsChange). Errors are kernel/errs errors without SQL: validation_failed with the
// pointer /handle or /display_name, conflict with /handle for a taken handle, not_found for an
// unknown principal, internal outside a unit of work.
type PrincipalWrites interface {
	// CreatePrincipal inserts the principal of cmd with status active and returns it.
	CreatePrincipal(ctx context.Context, cmd NewPrincipalCmd) (PrincipalView, error)
	// SetPrincipalStatus sets an agent or app principal active (clearing disabled_at) or
	// disabled (setting disabled_at to now); another status is validation_failed.
	SetPrincipalStatus(ctx context.Context, id ids.ID, status Status) error
	// UpdateDisplayName sets the display name of an agent or app principal under the rules of
	// NewPrincipalCmd.DisplayName.
	UpdateDisplayName(ctx context.Context, id ids.ID, name string) error
}
