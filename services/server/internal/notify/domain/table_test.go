// update rewrites testdata/decision_table.golden; the diff is reviewed like code.
var update = flag.Bool("update", false, "rewrite testdata/decision_table.golden")

const goldenPath = "testdata/decision_table.golden"

const goldenHeader = "# Decision table of internal/notify/domain (13 4.1); generated by TestDecisionTableGolden -update, checked against an oracle."

// combo is one row of the golden table: the inputs that 13 14 "Decision table" names.
type combo struct {
	kind          domain.Kind
	level         domain.Level
	muted         bool
	quietHours    bool
	breaksQuiet   bool
	adminEnabled  bool
	activeThread  bool
	desktopActive bool
	windowOpen    bool
}

// goldenNow is Friday 2026-10-23, 23:30 in Berlin: inside the quiet-hour rule of the table.
var goldenNow = time.Date(2026, 10, 23, 21, 30, 0, 0, time.UTC)

// combos enumerates every combination in the order of the golden file, each flag n before y.
func combos() []combo {
	var out []combo
	flags := []bool{false, true}
	for _, k := range domain.Kinds() {
		for _, l := range domain.Levels() {
			for _, muted := range flags {
				for _, qh := range flags {
					for _, br := range flags {
						for _, ad := range flags {
							for _, act := range flags {
								for _, desk := range flags {
									for _, win := range flags {
										out = append(out, combo{k, l, muted, qh, br, ad, act, desk, win})
									}
								}
							}
						}
					}
				}
			}
		}
	}
	return out
}

// factsFor builds the fixed facts of the table for one combination.
func factsFor(t testing.TB, c combo) domain.RecipientFacts {
	t.Helper()
	row := &domain.Preference{Level: c.level}
	if c.muted {
		row.MutedUntil = goldenNow.Add(time.Hour)
	}
	ph := domain.Device{ID: phoneID, Platform: domain.PlatformIOS, Registrations: []ids.ID{phoneReg}}
	if c.activeThread {
		ph.Connection = &domain.Connection{Focus: []ids.ID{threadID}}
	}
	desk := domain.Device{ID: desktopID, Platform: domain.PlatformMacOS}
	if c.desktopActive {
		desk.Connection = &domain.Connection{Focus: []ids.ID{otherThreadID}}
	}
	in := domain.RecipientFacts{
		Kind:       c.kind,
		Now:        goldenNow,
		Allowed:    true,
		RunStarter: true,
		Level: domain.LevelFacts{
			Thread:          row,
			DirectMessage:   c.kind == domain.KindDM,
			InstanceDefault: domain.LevelMentions,
		},
		Switches: domain.Switches{AdminEnabled: c.adminEnabled, InputNeededBreaksQuietHours: c.breaksQuiet},
		Devices:  []domain.Device{ph, desk},
		Policy:   domain.Policy{CoalesceWindow: time.Minute, MobileDelay: 30 * time.Second},
	}
	if c.kind != domain.KindSecurity && c.kind != domain.KindAdmin {
		in.ThreadID = threadID
	}
	if c.quietHours {
		in.QuietHours = []domain.QuietRule{nightRule(t)}
	}
	if c.windowOpen {
		in.Window = domain.Window{End: goldenNow.Add(30 * time.Second)}
	}
	return in
}

func yn(b bool) string {
	if b {
		return "y"
	}
	return "n"
}

func (c combo) key() string {
	return fmt.Sprintf("kind=%s level=%s muted=%s quiet_hours=%s breaks_quiet=%s admin_enabled=%s active_in_thread=%s desktop_active=%s window_open=%s",
		c.kind, c.level, yn(c.muted), yn(c.quietHours), yn(c.breaksQuiet), yn(c.adminEnabled), yn(c.activeThread), yn(c.desktopActive), yn(c.windowOpen))
}

var deviceNames = map[ids.ID]string{phoneID: "phone", desktopID: "desktop"}

// formatDecision writes the result columns of a golden line; offsets are relative to goldenNow.
func formatDecision(d domain.Decision) string {
	skip, effective, until, routes := "-", "-", "-", "-"
	if d.Skip != "" {
		skip = string(d.Skip)
	}
	if d.Effective.Level != "" {
		effective = string(d.Effective.Level)
	}
	if !d.OpensWindowUntil.IsZero() {
		until = fmt.Sprintf("+%ds", int(d.OpensWindowUntil.Sub(goldenNow).Seconds()))
	}
	if len(d.Routes) > 0 {
		parts := make([]string, 0, len(d.Routes))
		for _, r := range d.Routes {
			p := deviceNames[r.DeviceID] + ":" + string(r.Via)
			if !r.NotBefore.IsZero() {
				p += fmt.Sprintf("@+%ds", int(r.NotBefore.Sub(goldenNow).Seconds()))
			}
			parts = append(parts, p)
		}
		routes = strings.Join(parts, ",")
	}
	return fmt.Sprintf("outcome=%s skip=%s effective=%s quiet=%s count=%d window_until=%s routes=%s",
		d.Outcome, skip, effective, yn(d.Quiet), d.Count, until, routes)
}

// oracle computes the expected result columns from 13 2, 3.1, 3.4, 4.3, 4.4, 4.5 and 4.6 as plain
// boolean expressions, without calling a production helper.
func oracle(c combo) string {
	threadKind := c.kind != "security" && c.kind != "admin"
	effective := c.level
	if c.muted {
		effective = "mute" // 13 3.1: muted_until in the future on the chosen row
	}
	levelAllows := effective == "all" ||
		(effective == "mentions" && c.kind != "message") ||
		(effective == "mute" && c.kind == "input_needed")
	eff := "-"
	if threadKind {
		eff = string(effective)
	}
	none := func(skip string) string {
		return "outcome=none skip=" + skip + " effective=" + eff + " quiet=n count=0 window_until=- routes=-"
	}
	switch {
	case threadKind && !levelAllows:
		return none("level")
	case c.kind == "admin" && !c.adminEnabled:
		return none("admin_disabled")
	case threadKind && c.activeThread:
		return none("active_in_thread")
	case c.kind == "message" && c.windowOpen:
		return "outcome=collect skip=- effective=" + eff + " quiet=n count=0 window_until=- routes=-"
	}
	quiet := c.quietHours && (c.kind != "input_needed" || !c.breaksQuiet)
	phone := "phone:push"
	switch {
	case c.activeThread: // connected (only reachable for security and admin)
		phone = "phone:gateway"
	case c.desktopActive:
		phone = "phone:push_delayed@+30s"
	}
	routes := phone
	if c.desktopActive {
		routes += ",desktop:gateway"
	}
	until := "-"
	if threadKind && !c.windowOpen {
		until = "+60s"
	}
	return "outcome=send skip=- effective=" + eff + " quiet=" + yn(quiet) + " count=1 window_until=" + until + " routes=" + routes
}

// TestDecisionTableGolden enumerates every combination of 13 14 "Decision table" and holds
// the result against the golden file and against the oracle.
func TestDecisionTableGolden(t *testing.T) {
	t.Parallel()
	var buf bytes.Buffer
	buf.WriteString(goldenHeader + "\n")
	for _, c := range combos() {
		d, err := domain.Decide(factsFor(t, c))
		if err != nil {
			t.Fatalf("%s: %v", c.key(), err)
		}
		got := formatDecision(d)
		if want := oracle(c); got != want {
			t.Errorf("%s:\n got    %s\n oracle %s", c.key(), got, want)
		}
		buf.WriteString(c.key() + " -> " + got + "\n")
	}
	if *update {
		if err := os.WriteFile(goldenPath, buf.Bytes(), 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(filepath.FromSlash(goldenPath))
	if err != nil {
		t.Fatalf("read %s: %v (run with -update to create it)", goldenPath, err)
	}
	compareLines(t, want, buf.Bytes())
}

// compareLines names the first differing line of the golden file.
func compareLines(t *testing.T, want, got []byte) {
	t.Helper()
	ws, gs := bufio.NewScanner(bytes.NewReader(want)), bufio.NewScanner(bytes.NewReader(got))
	ws.Buffer(make([]byte, 0, 4096), 1<<20)
	gs.Buffer(make([]byte, 0, 4096), 1<<20)
	for n := 1; ; n++ {
		wok, gok := ws.Scan(), gs.Scan()
		if !wok && !gok {
			return
		}
		if wok != gok || ws.Text() != gs.Text() {
			t.Fatalf("%s line %d differs:\n file %q\n now  %q\nrun go test -run TestDecisionTableGolden -update and review the diff", goldenPath, n, ws.Text(), gs.Text())
		}
	}
}

// TestDecisionTableGolden_Size: the table has every combination exactly once.
func TestDecisionTableGolden_Size(t *testing.T) {
	t.Parallel()
	all := combos()
	if want := 8 * 3 * 2 * 2 * 2 * 2 * 2 * 2 * 2; len(all) != want {
		t.Fatalf("%d combinations, want %d", len(all), want)
	}
	seen := map[string]bool{}
	for _, c := range all {
		if seen[c.key()] {
			t.Fatalf("%s twice", c.key())
		}
		seen[c.key()] = true
	}
}
